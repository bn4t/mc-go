// Command genpotions extracts the vanilla potion-brewing mix table
// from PotionBrewing.addVanillaMixes bytecode. The mixes live in code,
// not datapack JSON, so javap is the authoritative source: each
// Builder call reads as getstatic Potions.X / Items.Y operands feeding
// an addMix(fromPotion, ingredient, toPotion),
// addContainerRecipe(fromItem, ingredient, toItem),
// addContainer(item) or addStartMix(ingredient, toPotion) — the last
// expands to WATER+ingredient->MUNDANE and AWKWARD+ingredient->potion,
// verified in PotionBrewing$Builder.
//
// Usage: go run ./tools/genpotions <vanilla-jar-extract-dir> <registries.json>
// Writes internal/data/potionmix_gen.go.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"regexp"
	"sort"
	"strings"
)

var (
	fieldRe = regexp.MustCompile(`Field net/minecraft/world/(?:item/Items|item/alchemy/Potions)\.([A-Z_]+)`)
	callRe  = regexp.MustCompile(`Method net/minecraft/world/item/alchemy/PotionBrewing\$Builder\.(addMix|addStartMix|addContainerRecipe|addContainer)`)
)

func lower(s string) string { return strings.ToLower(s) }

// potionIDsFromReport reads protocol_id per entry out of
// vanilla/reports/registries.json's minecraft:potion registry.
func potionIDsFromReport(path string) map[string]int32 {
	raw, err := os.ReadFile(path)
	if err != nil {
		fmt.Fprintf(os.Stderr, "registries: %v\n", err)
		os.Exit(1)
	}
	var regs map[string]struct {
		Entries map[string]struct {
			ProtocolID int32 `json:"protocol_id"`
		} `json:"entries"`
	}
	if err := json.Unmarshal(raw, &regs); err != nil {
		fmt.Fprintf(os.Stderr, "registries parse: %v\n", err)
		os.Exit(1)
	}
	pot, ok := regs["minecraft:potion"]
	if !ok {
		fmt.Fprintln(os.Stderr, "minecraft:potion registry missing")
		os.Exit(1)
	}
	ids := map[string]int32{}
	for name, e := range pot.Entries {
		ids[strings.TrimPrefix(name, "minecraft:")] = e.ProtocolID
	}
	return ids
}

func main() {
	jarDir, regJSON := os.Args[1], os.Args[2]
	out, err := exec.Command("javap", "-c", "-p", "-cp", jarDir,
		"net.minecraft.world.item.alchemy.PotionBrewing").CombinedOutput()
	if err != nil {
		fmt.Fprintf(os.Stderr, "javap: %v\n%s\n", err, out)
		os.Exit(1)
	}
	// keep only the addVanillaMixes body
	text := string(out)
	start := strings.Index(text, "public static void addVanillaMixes")
	if start < 0 {
		fmt.Fprintln(os.Stderr, "addVanillaMixes not found")
		os.Exit(1)
	}
	rest := text[start:]
	if end := strings.Index(rest, "\n  public static"); end > 0 {
		rest = rest[:end]
	}

	type mix struct{ from, ing, to string }
	var potionMixes []mix
	var containerMixes []mix
	var containers []string
	var pending []string // operand stack of field names
	flush := func() { pending = pending[:0] }
	for _, line := range strings.Split(rest, "\n") {
		if m := fieldRe.FindStringSubmatch(line); m != nil {
			pending = append(pending, lower(m[1]))
			continue
		}
		c := callRe.FindStringSubmatch(line)
		if c == nil {
			continue
		}
		switch c[1] {
		case "addContainer":
			containers = append(containers, pending[0])
		case "addContainerRecipe":
			containerMixes = append(containerMixes, mix{pending[0], pending[1], pending[2]})
		case "addMix":
			potionMixes = append(potionMixes, mix{pending[0], pending[1], pending[2]})
		case "addStartMix":
			potionMixes = append(potionMixes,
				mix{"water", pending[0], "mundane"},
				mix{"awkward", pending[0], pending[1]})
		}
		flush()
	}
	sort.Slice(potionMixes, func(i, j int) bool {
		if potionMixes[i].from != potionMixes[j].from {
			return potionMixes[i].from < potionMixes[j].from
		}
		return potionMixes[i].ing < potionMixes[j].ing
	})
	sort.Slice(containerMixes, func(i, j int) bool {
		if containerMixes[i].from != containerMixes[j].from {
			return containerMixes[i].from < containerMixes[j].from
		}
		return containerMixes[i].ing < containerMixes[j].ing
	})
	ingset := map[string]bool{}
	for _, m := range potionMixes {
		ingset[m.ing] = true
	}
	for _, m := range containerMixes {
		ingset[m.ing] = true
	}
	ings := make([]string, 0, len(ingset))
	for i := range ingset {
		ings = append(ings, i)
	}
	sort.Strings(ings)

	var b strings.Builder
	b.WriteString(`// Code generated by tools/genpotions from the vanilla
// PotionBrewing.addVanillaMixes bytecode; do not edit by hand.

package data

// PotionMixes maps {from-potion, ingredient item} to the brewed potion
// name, all minecraft: stripped. Both maps are what
// PotionBrewing.mix applies to every potion-slot stack when a brew
// finishes.
var PotionMixes = map[[2]string]string{
`)
	for _, m := range potionMixes {
		fmt.Fprintf(&b, "\t{%q, %q}: %q,\n", m.from, m.ing, m.to)
	}
	b.WriteString(`}

// ContainerMixes maps {from-item, ingredient item} to the container
// item the stack becomes (potion->splash_potion->lingering_potion),
// keeping the potion_contents.
var ContainerMixes = map[[2]string]string{
`)
	for _, m := range containerMixes {
		fmt.Fprintf(&b, "\t{%q, %q}: %q,\n", m.from, m.ing, m.to)
	}
	b.WriteString(`}

// BrewingContainers are the item ids a brewing stand's potion slots
// accept (Builder.addContainer), in registration order.
var BrewingContainers = []string{
`)
	for _, c := range containers {
		fmt.Fprintf(&b, "\t%q,\n", c)
	}
	b.WriteString(`}

// BrewingIngredientItems is every item that appears as an ingredient
// in a potion or container mix — the ingredient slot's accept set.
var BrewingIngredientItems = []string{
`)
	for _, i := range ings {
		fmt.Fprintf(&b, "\t%q,\n", i)
	}
	b.WriteString(`}

// PotionIDs maps minecraft:stripped potion names to their wire
// registry ids. The potion registry is static — vanilla never syncs
// it in Registry Data — so the ids come from the datagen report.
var PotionIDs = map[string]int32{
`)
	ids := potionIDsFromReport(regJSON)
	names := make([]string, 0, len(ids))
	for n := range ids {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q: %d,\n", n, ids[n])
	}
	b.WriteString("}\n")
	if err := os.WriteFile("internal/data/potionmix_gen.go", []byte(b.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Printf("potion mixes=%d container mixes=%d ingredients=%d potion ids=%d\n",
		len(potionMixes), len(containerMixes), len(ings), len(ids))
}
