// Command gentooltransforms measures block-to-block tool mappings through the
// installed vanilla runtime. It extracts registry facts, never method bodies.
package main

import (
	"bytes"
	"crypto/sha1"
	_ "embed"
	"flag"
	"fmt"
	"go/format"
	"io/fs"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

//go:embed probe.java
var probe []byte

func digest(path string) string {
	data, err := os.ReadFile(path)
	if err != nil {
		log.Fatal(err)
	}
	return fmt.Sprintf("%x", sha1.Sum(data))
}

func run(name string, args ...string) []byte {
	output, err := exec.Command(name, args...).CombinedOutput()
	if err != nil {
		log.Fatalf("%s: %v\n%s", name, err, output)
	}
	return output
}

func main() {
	vanilla := flag.String("vanilla", "vanilla", "unpacked vanilla runtime directory")
	output := flag.String("out", "internal/server/tooltransforms_gen.go", "generated Go output")
	flag.Parse()
	runtimeJar := filepath.Join(*vanilla, "versions", "26.2", "server-26.2.jar")
	jars := []string{runtimeJar}
	err := filepath.WalkDir(filepath.Join(*vanilla, "libraries"), func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !entry.IsDir() && strings.HasSuffix(path, ".jar") {
			jars = append(jars, path)
		}
		return nil
	})
	if err != nil {
		log.Fatal(err)
	}
	sort.Strings(jars[1:])
	classpath := strings.Join(jars, string(os.PathListSeparator))
	temp, err := os.MkdirTemp("", "mcgo-tool-facts-")
	if err != nil {
		log.Fatal(err)
	}
	defer os.RemoveAll(temp)
	javaFile := filepath.Join(temp, "ToolFactsProbe.java")
	if err := os.WriteFile(javaFile, probe, 0600); err != nil {
		log.Fatal(err)
	}
	run("javac", "-cp", classpath, "-d", temp, javaFile)
	facts := run("java", "-Xmx512m", "-cp", classpath+string(os.PathListSeparator)+temp, "ToolFactsProbe")
	names := [][2]string{{"STRIPPABLES", "toolStrippables"}, {"PREVIOUS_BY_BLOCK", "toolCopperPrevious"}, {"WAX_OFF_BY_BLOCK", "toolWaxOff"}, {"WAXABLES", "toolWaxOn"}}
	tables := map[string]map[string]string{}
	for _, pair := range names {
		tables[pair[0]] = map[string]string{}
	}
	const marker = "MCGO_TOOL_FACT\t"
	for _, line := range strings.Split(string(facts), "\n") {
		start := strings.Index(line, marker)
		if start < 0 {
			continue
		}
		parts := strings.Split(strings.TrimSpace(line[start+len(marker):]), "\t")
		if len(parts) != 3 {
			log.Fatalf("invalid fact %q", line)
		}
		table, ok := tables[parts[0]]
		if !ok {
			log.Fatalf("unknown table %q", parts[0])
		}
		from, to := strings.TrimPrefix(parts[1], "minecraft:"), strings.TrimPrefix(parts[2], "minecraft:")
		if previous, ok := table[from]; ok && previous != to {
			log.Fatalf("conflicting fact %q", line)
		}
		table[from] = to
	}
	var generated bytes.Buffer
	fmt.Fprintln(&generated, "// Code generated by go run ./tools/gentooltransforms; DO NOT EDIT.")
	fmt.Fprintf(&generated, "// Java26.2 runtime registry maps: AxeItem, WeatheringCopper, HoneycombItem.\n// Bundle SHA1: %s\n// Runtime SHA1: %s\n\npackage server\n\n", digest(filepath.Join(*vanilla, "server-26.2.jar")), digest(runtimeJar))
	for _, pair := range names {
		table := tables[pair[0]]
		if len(table) == 0 {
			log.Fatalf("empty table %s", pair[0])
		}
		keys := make([]string, 0, len(table))
		for name := range table {
			keys = append(keys, name)
		}
		sort.Strings(keys)
		fmt.Fprintf(&generated, "var %s = map[string]string{\n", pair[1])
		for _, name := range keys {
			fmt.Fprintf(&generated, "%q: %q,\n", name, table[name])
		}
		fmt.Fprintln(&generated, "}")
		log.Printf("%s: %d mappings", pair[0], len(table))
	}
	formatted, err := format.Source(generated.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*output, formatted, 0644); err != nil {
		log.Fatal(err)
	}
}
