// Command genblast extracts per-block explosion resistance from the
// vanilla jar's Blocks.<clinit> bytecode: inside each field's
// register(...) segment the Properties chain's strength(F|FF),
// instabreak(), explosionResistance(F) and ofFullCopy/ofLegacyCopy
// calls determine the final explosionResistance value. Emits
// internal/server/blastresist_gen.go. Run:
//
//	javap -c -classpath <jardir> net.minecraft.world.level.block.Blocks | \
//	  go run ./tools/genblast > internal/server/blastresist_gen.go
package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strconv"
	"strings"
)

var (
	rePutstatic = regexp.MustCompile(`putstatic.*// Field (\w+):Lnet/minecraft/world/level/block/Block;`)
	reFconst    = regexp.MustCompile(`fconst_(\d)`)
	reLdc       = regexp.MustCompile(`// float ([-\d.eE]+)f`)
	reStrength1 = regexp.MustCompile(`Properties\.strength:\(F\)`)
	reStrength2 = regexp.MustCompile(`Properties\.strength:\(FF\)`)
	reResist    = regexp.MustCompile(`Properties\.explosionResistance:\(F\)`)
	reInsta     = regexp.MustCompile(`Properties\.instabreak:\(\)`)
	reCopy      = regexp.MustCompile(`of(?:Full|Legacy)Copy:`)
	reCopyRef   = regexp.MustCompile(`getstatic.*// Field (\w+):Lnet/minecraft/world/level/block/Block;`)
	reInvoke    = regexp.MustCompile(`invoke(virtual|static|interface|special|dynamic)`)
	reHelper    = regexp.MustCompile(`Method (logProperties|leavesProperties|pistonProperties|buttonProperties|flowerPotProperties|netherStemProperties|candleProperties|shulkerBoxProperties):`)
)

// helperResist is the explosion resistance each Blocks.<clinit>
// Properties-factory bakes in (measured on the helpers' bytecode:
// strength(f) means resist f, instabreak() means 0).
var helperResist = map[string]float64{
	"logProperties":        2,
	"leavesProperties":     0.2,
	"pistonProperties":     1.5,
	"buttonProperties":     0.5,
	"flowerPotProperties":  0,
	"netherStemProperties": 2,
	"candleProperties":     0.1,
	"shulkerBoxProperties": 2,
}

type seg struct {
	name      string
	resist    float64
	hasResist bool
	copyOf    string
	helper    string
}

func main() {
	var segs []*seg
	var cur *seg
	var pending []float64
	var lastGet string // last getstatic block-field ref (copy target)

	finish := func(name string) {
		if cur == nil {
			// a field with no register segment at all
			cur = &seg{}
		}
		cur.name = name
		segs = append(segs, cur)
		cur = nil
		pending = nil
		lastGet = ""
	}
	ensure := func() {
		if cur == nil {
			cur = &seg{}
		}
	}
	consume := func() { pending = nil }

	sc := bufio.NewScanner(os.Stdin)
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	for sc.Scan() {
		l := sc.Text()
		if m := rePutstatic.FindStringSubmatch(l); m != nil {
			finish(m[1])
			continue
		}
		if m := reLdc.FindStringSubmatch(l); m != nil {
			f, _ := strconv.ParseFloat(m[1], 64)
			pending = append(pending, f)
			continue
		}
		if m := reFconst.FindStringSubmatch(l); m != nil {
			f, _ := strconv.ParseFloat(m[1], 64)
			pending = append(pending, f)
			continue
		}
		if reInvoke.MatchString(l) {
			switch {
			case reStrength2.MatchString(l):
				ensure()
				if len(pending) >= 2 {
					cur.resist, cur.hasResist = pending[len(pending)-1], true
				}
			case reStrength1.MatchString(l):
				ensure()
				if len(pending) >= 1 {
					cur.resist, cur.hasResist = pending[len(pending)-1], true
				}
			case reResist.MatchString(l):
				ensure()
				if len(pending) >= 1 {
					cur.resist, cur.hasResist = pending[len(pending)-1], true
				}
			case reInsta.MatchString(l):
				ensure()
				cur.resist, cur.hasResist = 0, true
			case reCopy.MatchString(l):
				ensure()
				cur.copyOf = lastGet
			default:
				if m := reHelper.FindStringSubmatch(l); m != nil {
					ensure()
					cur.helper = m[1]
				}
			}
			consume()
			continue
		}
		if m := reCopyRef.FindStringSubmatch(l); m != nil {
			lastGet = m[1]
			continue
		}
	}

	res := map[string]float64{}
	seen := map[string]bool{}
	for _, s := range segs {
		res[s.name] = s.resist
		seen[s.name] = seen[s.name] || s.hasResist
	}
	for _, s := range segs {
		if !s.hasResist && s.helper != "" {
			s.resist, s.hasResist = helperResist[s.helper], true
		}
	}
	for _, s := range segs {
		if s.copyOf != "" && !s.hasResist {
			s.resist = res[s.copyOf]
		}
	}
	fmt.Println(`// Code generated by tools/genblast from the vanilla 26.2
// Blocks.<clinit> bytecode (strength/instabreak/explosionResistance
// args). Do not edit.
package server

// blastResistance is Block.getExplosionResistance by block name. A
// missing name resists 0 — vanilla Properties.of() defaults the field
// to 0 too. Fluids carry their own resistance (water/lava 100)
// applied via max() in the sampler, not through this table.
var blastResistance = map[string]float32{`)
	for _, s := range segs {
		if s.resist != 0 {
			fmt.Printf("\t%q: %v,\n", strings.ToLower(s.name), s.resist)
		}
	}
	fmt.Println("}")
}
