// Command genblockmapping joins official block reports by canonical full state,
// producing protocol numeric projections without inferring absent states.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"runtime"

	"mc-go/api/registry"
)

type report map[string]struct {
	States []struct {
		ID         int32             `json:"id"`
		Properties map[string]string `json:"properties"`
	} `json:"states"`
}
type stateReport struct {
	states []registry.StateKey
	ids    map[registry.StateKey]int32
	hash   string
}

func load(path string) (stateReport, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return stateReport{}, err
	}
	var doc report
	if err = json.Unmarshal(raw, &doc); err != nil {
		return stateReport{}, err
	}
	max := int32(-1)
	for _, block := range doc {
		for _, state := range block.States {
			if state.ID < 0 || state.ID >= 1<<20 {
				return stateReport{}, fmt.Errorf("invalid report state ID %d", state.ID)
			}
			if state.ID > max {
				max = state.ID
			}
		}
	}
	out := stateReport{states: make([]registry.StateKey, int(max)+1), ids: map[registry.StateKey]int32{}, hash: fmt.Sprintf("%x", sha256.Sum256(raw))}
	for name, block := range doc {
		for _, state := range block.States {
			key, err := registry.NewStateKey(name, state.Properties)
			if err != nil {
				return stateReport{}, err
			}
			if out.states[state.ID].Valid() {
				return stateReport{}, fmt.Errorf("duplicate report state ID %d", state.ID)
			}
			if _, exists := out.ids[key]; exists {
				return stateReport{}, fmt.Errorf("duplicate canonical report state %s", key)
			}
			out.states[state.ID] = key
			out.ids[key] = state.ID
		}
	}
	for id, key := range out.states {
		if !key.Valid() {
			return stateReport{}, fmt.Errorf("report hole at %d", id)
		}
	}
	return out, nil
}
func run() error {
	sourcePath := flag.String("source", "vanilla/measure-26.1/generated/reports/blocks.json", "official source protocol block report")
	targetPath := flag.String("target", "vanilla/measure-26.2/generated/reports/blocks.json", "official builtin runtime catalog block report")
	protocol := flag.Int("protocol", 775, "source numeric protocol")
	version := flag.String("version", "26.1", "source version")
	jarHash := flag.String("jar-sha256", "", "source official server JAR SHA256 provenance")
	output := flag.String("output", "internal/world/protocol775_gen.go", "generated Go output")
	flag.Parse()
	if *protocol != 775 {
		return fmt.Errorf("this initial generator output is named for protocol775 only")
	}
	source, err := load(*sourcePath)
	if err != nil {
		return err
	}
	target, err := load(*targetPath)
	if err != nil {
		return err
	}
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by tools/genblockmapping from official datagen block reports; DO NOT EDIT.")
	fmt.Fprintf(&out, "// Source class: official report, Java %s / protocol %d, JDK 25 datagen --reports.\n", *version, *protocol)
	fmt.Fprintf(&out, "// Source JAR SHA256: %s\n", *jarHash)
	fmt.Fprintf(&out, "// Source blocks.json SHA256: %s\n", source.hash)
	fmt.Fprintf(&out, "// Builtin protocol776 blocks.json SHA256: %s\n", target.hash)
	fmt.Fprintf(&out, "// Generator toolchain: %s. Missing canonical states are -1, never inferred.\n\npackage world\n\n", runtime.Version())
	fmt.Fprintf(&out, "const protocol775SourceStateCount = %d\n\n", len(source.states))
	fmt.Fprintln(&out, "// protocol775BlockStates indexes builtin runtime handles and stores measured775 IDs.")
	fmt.Fprintln(&out, "var protocol775BlockStates = [...]int32{")
	matched, renumbered := 0, 0
	for runtime, key := range target.states {
		wire, ok := source.ids[key]
		if !ok {
			wire = -1
		} else {
			matched++
			if wire != int32(runtime) {
				renumbered++
			}
		}
		if runtime%16 == 0 {
			fmt.Fprint(&out, "\t")
		}
		fmt.Fprintf(&out, "%d,", wire)
		if runtime%16 == 15 {
			fmt.Fprintln(&out)
		} else {
			fmt.Fprint(&out, " ")
		}
	}
	fmt.Fprintln(&out, "\n}")
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return err
	}
	if err = os.WriteFile(*output, formatted, 0644); err != nil {
		return err
	}
	fmt.Printf("generated %s: runtime=%d source=%d exact=%d missing=%d renumbered=%d\n", *output, len(target.states), len(source.states), matched, len(target.states)-matched, renumbered)
	return nil
}
func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
