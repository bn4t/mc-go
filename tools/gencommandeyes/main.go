// gencommandeyes projects measured dimension data into runtime eye tables.
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strconv"
	"strings"
	"unicode"
)

func main() {
	input := flag.String("in", "tools/gencommandeyes/public-dimensions.tsv", "normalized getter fixture")
	output := flag.String("out", "internal/server/commandeyes_generated.go", "generated Go table")
	check := flag.Bool("check", false, "check exact generated bytes")
	flag.Parse()
	if err := run(*input, *output, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
func snake(s string) string {
	var b strings.Builder
	for i, r := range s {
		if i > 0 && unicode.IsUpper(r) {
			b.WriteByte('_')
		}
		b.WriteRune(unicode.ToLower(r))
	}
	return b.String()
}
func generate(raw []byte) ([]byte, error) {
	adult, baby := map[string]string{}, map[string]string{}
	variants := 0
	scan := bufio.NewScanner(bytes.NewReader(raw))
	line := 0
	for scan.Scan() {
		line++
		text := scan.Text()
		if strings.HasPrefix(text, "#") || text == "" {
			continue
		}
		a := strings.Split(text, "\t")
		kind := a[0]
		want := 5
		if kind == "variant" {
			want = 6
		}
		if kind != "type" && kind != "variant" || len(a) != want {
			return nil, fmt.Errorf("line%d invalid row", line)
		}
		for _, v := range a[want-3:] {
			f, err := strconv.ParseFloat(v, 32)
			if err != nil || f < 0 || f != f || f > 1e6 {
				return nil, fmt.Errorf("line%d invalid dimension %q", line, v)
			}
		}
		value := a[want-1]
		if kind == "type" {
			if _, ok := adult[a[1]]; ok {
				return nil, fmt.Errorf("duplicate type %q", a[1])
			}
			adult[a[1]] = value
			continue
		}
		variants++
		if a[2] != "BABY_DIMENSIONS" && !(a[2] == "BABY_STANDING_DIMENSIONS" && strings.HasSuffix(a[1], ".Camel")) {
			continue
		}
		parts := strings.Split(a[1], ".")
		name := parts[len(parts)-1]
		if name == "AbstractCow" || name == "ArmorStand" {
			continue
		}
		name = snake(name)
		if name == "mushroom_cow" {
			name = "mooshroom"
		}
		if _, ok := baby[name]; ok {
			return nil, fmt.Errorf("duplicate baby type %q", name)
		}
		baby[name] = value
	}
	if err := scan.Err(); err != nil {
		return nil, err
	}
	if len(adult) != 158 || variants != 44 || len(baby) != 35 {
		return nil, fmt.Errorf("incomplete fixture: types%d variants%d baby%d", len(adult), variants, len(baby))
	}
	// These inherited eye constants are independently pinned on native entities.
	baby["glow_squid"] = baby["squid"]
	baby["trader_llama"] = baby["llama"]
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by go run ./tools/gencommandeyes; DO NOT EDIT.\n// Input SHA256: %x\npackage server\n\n", sha256.Sum256(raw))
	for _, table := range []struct {
		name   string
		values map[string]string
	}{{"commandTypeEyes", adult}, {"commandBabyEyes", baby}} {
		fmt.Fprintf(&out, "var %s = map[string]float32{\n", table.name)
		keys := make([]string, 0, len(table.values))
		for k := range table.values {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		for _, k := range keys {
			fmt.Fprintf(&out, "%q: %s,\n", k, table.values[k])
		}
		out.WriteString("}\n")
	}
	return format.Source(out.Bytes())
}
func run(input, output string, check bool) error {
	raw, err := os.ReadFile(input)
	if err != nil {
		return err
	}
	generated, err := generate(raw)
	if err != nil {
		return err
	}
	if check {
		old, err := os.ReadFile(output)
		if err != nil {
			return err
		}
		if !bytes.Equal(old, generated) {
			return fmt.Errorf("%s differs from generated fixture", output)
		}
		return nil
	}
	return os.WriteFile(output, generated, 0644)
}
