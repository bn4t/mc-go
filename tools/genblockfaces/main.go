// Command genblockfaces measures, by runtime reflection against the local
// official 26.2 server distribution, which block states have a collision
// shape whose top face is full, and emits internal/server/blockfaces_gen.go.
// It does not decompile or translate methods: the probe only asks the
// running game for each state's shape and the face fact. Regeneration
// needs JDK 25 and the unpacked server (vanilla/versions, vanilla/libraries).
//
// Usage: go run ./tools/genblockfaces [-jdk dir] [-root .]
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"flag"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

func main() {
	jdk := flag.String("jdk", "", "directory containing java and javac, otherwise PATH")
	root := flag.String("root", ".", "repository root")
	flag.Parse()
	base := filepath.Join(*root, "vanilla")
	jar := filepath.Join(base, "versions", "26.2", "server-26.2.jar")
	classpath := []string{jar}
	must(filepath.WalkDir(filepath.Join(base, "libraries"), func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() && strings.HasSuffix(path, ".jar") {
			classpath = append(classpath, path)
		}
		return nil
	}))
	sort.Strings(classpath[1:])
	cp := strings.Join(classpath, string(os.PathListSeparator))
	temp, err := os.MkdirTemp("", "mcgo-block-faces-")
	must(err)
	defer os.RemoveAll(temp)
	run(filepath.Join(*jdk, "javac"), "-cp", cp, "-d", temp, filepath.Join(*root, "tools/genblockfaces/FaceProbe.java"))
	out := filepath.Join(temp, "faces.tsv")
	run(filepath.Join(*jdk, "java"), "-cp", temp+string(os.PathListSeparator)+cp, "FaceProbe", out)
	raw, err := os.ReadFile(out)
	must(err)

	full := map[int]bool{}
	maxID, count := -1, 0
	sc := bufio.NewScanner(bytes.NewReader(raw))
	for sc.Scan() {
		f := strings.Split(sc.Text(), "\t")
		if f[0] == "count" {
			count, err = strconv.Atoi(f[1])
			must(err)
			continue
		}
		id, err := strconv.Atoi(f[0])
		must(err)
		if id > maxID {
			maxID = id
		}
		if f[2] == "1" {
			full[id] = true
		}
	}
	if count != maxID+1 {
		fatal("state ids not dense: %d states, max id %d", count, maxID)
	}
	words := make([]uint64, (count+63)/64)
	for id := range full {
		words[id/64] |= 1 << (id % 64)
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tools/genblockfaces; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// Source: runtime reflection over the official 26.2 server jar\n")
	fmt.Fprintf(&b, "// (SHA-256 %x), measurement SHA-256 %x.\n\n", sha256OfFile(jar), sha256.Sum256(raw))
	fmt.Fprintf(&b, "package server\n\n")
	fmt.Fprintf(&b, "// topFaceFullBits holds one bit per block state id: set when the\n")
	fmt.Fprintf(&b, "// state's collision shape covers its whole top face. %d of %d\n", len(full), count)
	fmt.Fprintf(&b, "// states measure full.\n")
	fmt.Fprintf(&b, "var topFaceFullBits = [%d]uint64{", len(words))
	for i, w := range words {
		if i%4 == 0 {
			b.WriteString("\n\t")
		} else {
			b.WriteString(" ")
		}
		fmt.Fprintf(&b, "%#016x,", w)
	}
	b.WriteString("\n}\n\n")
	fmt.Fprintf(&b, "// blockStateCount is the number of measured block states.\n")
	fmt.Fprintf(&b, "const blockStateCount = %d\n", count)
	src, err := format.Source(b.Bytes())
	must(err)
	must(os.WriteFile(filepath.Join(*root, "internal/server/blockfaces_gen.go"), src, 0644))
}

func sha256OfFile(path string) [32]byte {
	raw, err := os.ReadFile(path)
	must(err)
	return sha256.Sum256(raw)
}

func run(command string, args ...string) {
	out, err := exec.Command(command, args...).CombinedOutput()
	if err != nil {
		fatal("%s: %v\n%s", command, err, out)
	}
}

func must(err error) {
	if err != nil {
		fatal("%v", err)
	}
}

func fatal(message string, args ...any) { fmt.Fprintf(os.Stderr, message+"\n", args...); os.Exit(1) }
