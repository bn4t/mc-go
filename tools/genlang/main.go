// Command genlang turns the vanilla jar's en_us.json into the
// translation table mc-go ships, so console-style sinks (RCON, logs)
// can render translatable components to the same English text the
// real server sends.
//
// The table is data, not code: it is the same file the vanilla server
// loads for its own flat rendering, so the generated map is exact by
// construction.
//
// Usage (from the repo root):
//
//	go run ./tools/genlang
package main

import (
	"archive/zip"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strconv"
	"strings"
)

const (
	jarPath  = "vanilla/versions/26.2/server-26.2.jar"
	langFile = "assets/minecraft/lang/en_us.json"
	outPath  = "internal/server/langtext_gen.go"
)

func main() {
	r, err := zip.OpenReader(jarPath)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer r.Close()
	var data []byte
	for _, f := range r.File {
		if f.Name != langFile {
			continue
		}
		rc, err := f.Open()
		if err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		buf := new(strings.Builder)
		tmp := make([]byte, 1<<15)
		for {
			n, err := rc.Read(tmp)
			buf.Write(tmp[:n])
			if err != nil {
				break
			}
		}
		rc.Close()
		data = []byte(buf.String())
	}
	if data == nil {
		fmt.Fprintln(os.Stderr, langFile+" not in "+jarPath)
		os.Exit(1)
	}
	var table map[string]string
	if err := json.Unmarshal(data, &table); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	keys := make([]string, 0, len(table))
	for k := range table {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var b strings.Builder
	b.WriteString(`// Code generated by tools/genlang; DO NOT EDIT.
//
// langEnUS is the vanilla 26.2 assets/minecraft/lang/en_us.json
// verbatim: component translation lookups (RCON, logs, any non-NBT
// sink) resolve through it exactly like the real server's Language.

package server

var langEnUS = map[string]string{
`)
	for _, k := range keys {
		b.WriteString(strconv.Quote(k) + ": " + strconv.Quote(table[k]) + ",\n")
	}
	b.WriteString("}\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(outPath, src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Println(len(table), "translations ->", outPath)
}
