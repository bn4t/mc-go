// gensuffoc emits internal/server/blocksuffoc_gen.go: the set of block
// owner names whose vanilla isSuffocating (opaque full cube, canOcclude)
// is true, resolved from the blocks.json report's definition types.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"sort"
	"strings"
)

var suffocatingTypes = map[string]bool{
	"block": true, "rotated_pillar": true, "glazed_terracotta": true,
	"concrete_powder": true, "colored_falling": true, "sand": true,
	"grass": true, "mud": true, "mycelium": true, "snowy_dirt": true,
	"rooted_dirt": true, "infested": true, "weathering_copper_full": true,
	"drop_experience": true, "nylium": true, "magma": true,
	"pumpkin": true, "jack_o_lantern": true, "sponge": true,
	"wet_sponge": true, "mangrove_roots": true, "sculk": true,
	"crying_obsidian": true, "respawn_anchor": true, "amethyst": true,
	"budding_amethyst": true, "powered": true, "hay": true,
	"target": true, "furnace": true, "blast_furnace": true,
	"smoker": true, "dispenser": true, "dropper": true, "observer": true,
	"piston_base": true, "crafting_table": true, "smithing_table": true,
	"cartography_table": true, "note": true, "jukebox": true,
	"beehive": true, "tnt": true, "chiseled_book_shelf": true,
	"brushable": true, "sculk_catalyst": true, "trial_spawner": true,
	"vault": true, "crafter": true, "weathering_copper_bulb": true,
	"copper_bulb_block": true, "command": true, "barrel": true,
	"loom": true, "end_portal_frame": true,
	// Custom full-cube types the generic "block" type does not catch —
	// each is an opaque occluder in vanilla (measured: light entering a
	// netherrack pocket died at the wall, not inside it).
	"netherrack": true, "redstone_ore": true, "redstone_lamp": true,
	"jigsaw": true, "structure": true, "test": true,
	"test_instance": true, "barrier": true, "infested_rotated_pillar": true,
}

func main() {
	var report map[string]struct {
		Definition struct {
			Type string `json:"type"`
		} `json:"definition"`
	}
	f, err := os.Open("vanilla/reports/blocks.json")
	if err != nil {
		panic(err)
	}
	if err := json.NewDecoder(f).Decode(&report); err != nil {
		panic(err)
	}
	var names []string
	for name, b := range report {
		short := strings.TrimPrefix(name, "minecraft:")
		if suffocatingTypes[strings.TrimPrefix(b.Definition.Type, "minecraft:")] {
			names = append(names, short)
		}
	}
	sort.Strings(names)
	var sb strings.Builder
	sb.WriteString("package server\n\n// Code generated by tools/gensuffoc from vanilla/reports/blocks.json.\n\n")
	sb.WriteString("// suffocatingBlocks are the block owners whose vanilla\n")
	sb.WriteString("// isSuffocating (opaque full-cube canOcclude) is true — what\n")
	sb.WriteString("// Entity.isInWall's eye-plane scan matches.\nvar suffocatingBlocks = map[string]bool{\n")
	for _, n := range names {
		fmt.Fprintf(&sb, "\t%q: true,\n", n)
	}
	sb.WriteString("}\n")
	if err := os.WriteFile("internal/server/blocksuffoc_gen.go", []byte(sb.String()), 0o644); err != nil {
		panic(err)
	}
	fmt.Println("wrote", len(names), "suffocating blocks")
}
