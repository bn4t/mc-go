// Command geneffectattrs renders facts from the public 26.2 MobEffect.createModifiers
// API. Reproduce input by compiling/running PlayerEffectAttributesProbe.java with
// the runtime jar plus bundled libraries, keeping the tab fields after FACT.
package main

import (
	"crypto/sha256"
	"flag"
	"fmt"
	"go/format"
	"os"
	"strconv"
	"strings"
)

func main() {
	input := flag.String("facts", "internal/server/testdata/vanilla-26.2/effect_attributes.tsv", "public API facts")
	output := flag.String("out", "internal/server/playereffectattrs_gen.go", "generated Go table")
	flag.Parse()
	raw, err := os.ReadFile(*input)
	if err != nil {
		panic(err)
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by tools/geneffectattrs; DO NOT EDIT.\n// Minecraft Java26.2 runtime SHA1 86765a5899bd9c96461036a628796b4245715058.\n// Input SHA256 %x; public MobEffect.createModifiers(amplifier=0).\npackage server\n\nvar playerEffectAttributeTemplates = map[string][]playerEffectAttributeTemplate{\n", sha256.Sum256(raw))
	for _, line := range strings.Split(strings.TrimSpace(string(raw)), "\n") {
		parts := strings.Split(line, "\t")
		if len(parts) != 5 {
			panic(line)
		}
		amount, err := strconv.ParseFloat(parts[3], 64)
		if err != nil {
			panic(err)
		}
		op, valid := map[string]int{"add_value": 0, "add_multiplied_base": 1, "add_multiplied_total": 2}[parts[4]]
		if !valid {
			panic(parts[4])
		}
		fmt.Fprintf(&b, "%q: {{attribute:%q,id:%q,amount:%s,operation:%d}},\n", strings.TrimPrefix(parts[0], "minecraft:"), strings.TrimPrefix(parts[1], "minecraft:"), parts[2], strconv.FormatFloat(amount, 'g', -1, 64), op)
	}
	b.WriteString("}\n")
	data, err := format.Source([]byte(b.String()))
	if err != nil {
		panic(err)
	}
	if err = os.WriteFile(*output, data, 0644); err != nil {
		panic(err)
	}
}
