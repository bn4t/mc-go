// Command genjtrig records java.lang.Math.sin and cos as the JVM
// computes them, beside the correctly rounded values, as
// internal/worldgen/testdata/java_trig.tsv.gz. It compiles and runs
// TrigProbe.java, which uses only the JDK.
//
//	go run ./tools/genjtrig -jdk ~/opt/jdk25/bin
package main

import (
	"bytes"
	"compress/gzip"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

func main() {
	jdk := flag.String("jdk", "", "directory containing java and javac, otherwise PATH")
	root := flag.String("root", ".", "repository root")
	flag.Parse()
	temp, err := os.MkdirTemp("", "mcgo-jtrig-")
	must(err)
	defer os.RemoveAll(temp)
	run(filepath.Join(*jdk, "javac"), "-d", temp, filepath.Join(*root, "tools/genjtrig/TrigProbe.java"))
	out := filepath.Join(temp, "trig.tsv")
	run(filepath.Join(*jdk, "java"), "-cp", temp, "TrigProbe", out)
	version, err := exec.Command(filepath.Join(*jdk, "java"), "-XshowSettings:properties", "-version").CombinedOutput()
	must(err)
	jv := "unknown"
	for _, line := range strings.Split(string(version), "\n") {
		if v, ok := strings.CutPrefix(strings.TrimSpace(line), "java.runtime.version = "); ok {
			jv = v
		}
	}
	raw, err := os.ReadFile(out)
	must(err)
	var b bytes.Buffer
	w, err := gzip.NewWriterLevel(&b, gzip.BestCompression)
	must(err)
	fmt.Fprintf(w, "# Generated by tools/genjtrig (TrigProbe, JDK %s); DO NOT EDIT.\n", jv)
	_, err = w.Write(raw)
	must(err)
	must(w.Close())
	must(os.WriteFile(filepath.Join(*root, "internal/worldgen/testdata/java_trig.tsv.gz"), b.Bytes(), 0o644))
}

func run(command string, args ...string) {
	if out, err := exec.Command(command, args...).CombinedOutput(); err != nil {
		fmt.Fprintf(os.Stderr, "%s: %v\n%s", command, err, out)
		os.Exit(1)
	}
}

func must(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
