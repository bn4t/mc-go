// Command genpackets regenerates the complete protocol-776 packet-ID
// table from the report emitted by the vanilla server's built-in data
// generator (java -DbundlerMainClass=net.minecraft.data.Main -jar
// server.jar --reports). Reports are data, not code: they are the same
// ids the client and server hardcode, so the generated table is exact
// by construction.
//
// Usage (from the repo root):
//
//	go run ./tools/genpackets
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"sort"
	"strings"
)

// states is the report's state order, which the generated table keeps.
var states = []string{"handshake", "status", "login", "configuration", "play"}

var dirs = []string{"serverbound", "clientbound"}

func main() {
	raw, err := os.ReadFile("vanilla/reports/packets.json")
	if err != nil {
		fatalf("read report: %v (run the data generator first; see tool comment)", err)
	}
	var doc map[string]map[string]map[string]struct {
		ProtocolID int32 `json:"protocol_id"`
	}
	if err := json.Unmarshal(raw, &doc); err != nil {
		fatalf("parse report: %v", err)
	}

	var b strings.Builder
	b.WriteString("// Code generated by tools/genpackets from vanilla/reports/packets.json. DO NOT EDIT.\n\n")
	b.WriteString("package server\n\n")
	b.WriteString(`// Packet states and directions, spelled as in the official report.
const (
	PacketStateHandshake     = "handshake"
	PacketStateStatus        = "status"
	PacketStateLogin         = "login"
	PacketStateConfiguration = "configuration"
	PacketStatePlay          = "play"

	PacketDirServerbound = "serverbound"
	PacketDirClientbound = "clientbound"
)

// officialPacket is one row of the vanilla server's --reports packet
// table: the protocol id of a named packet in a state and direction.
type officialPacket struct {
	State string
	Dir   string
	Name  string // official name, without the minecraft: prefix
	ID    int32
}

// officialPackets is every packet in protocol 776, ordered by state,
// direction, then id. Tests use it as the source of truth for the
// protocol surface: coverage claims are checked against it, so a
// missing or invented packet id fails the build.
var officialPackets = []officialPacket{
`)

	total := 0
	for _, state := range states {
		for _, dir := range dirs {
			pk, ok := doc[state][dir]
			if !ok {
				continue
			}
			type row struct {
				name string
				id   int32
			}
			rows := make([]row, 0, len(pk))
			for name, m := range pk {
				rows = append(rows, row{strings.TrimPrefix(name, "minecraft:"), m.ProtocolID})
			}
			sort.Slice(rows, func(i, j int) bool {
				if rows[i].id != rows[j].id {
					return rows[i].id < rows[j].id
				}
				return rows[i].name < rows[j].name
			})
			for _, r := range rows {
				fmt.Fprintf(&b, "\t{PacketState%s, PacketDir%s, %q, 0x%02X},\n",
					title(state), title(dir), r.name, r.id)
				total++
			}
		}
	}
	b.WriteString("}\n\n")

	b.WriteString(`// officialIDs lists, in ascending order, the id of every packet in
// the given state and direction.
func officialIDs(state, dir string) []int32 {
	var out []int32
	for _, p := range officialPackets {
		if p.State == state && p.Dir == dir {
			out = append(out, p.ID)
		}
	}
	return out
}

// officialName returns the official name of the packet with this id.
func officialName(state, dir string, id int32) (string, bool) {
	for _, p := range officialPackets {
		if p.State == state && p.Dir == dir && p.ID == id {
			return p.Name, true
		}
	}
	return "", false
}

// officialID resolves a packet id by its official name. It panics when
// the name is unknown, so a version table that references a packet the
// report does not contain fails at start-up instead of silently
// shipping a wrong id.
func officialID(state, dir, name string) int32 {
	for _, p := range officialPackets {
		if p.State == state && p.Dir == dir && p.Name == name {
			return p.ID
		}
	}
	panic("unknown packet " + state + "/" + dir + "/" + name)
}
`)

	if err := os.WriteFile("internal/server/packetids_gen.go", []byte(b.String()), 0o644); err != nil {
		fatalf("write: %v", err)
	}
	fmt.Printf("generated internal/server/packetids_gen.go (%d packets)\n", total)
}

// title upper-cases the first letter so state and direction constants
// read as PacketStatePlay / PacketDirServerbound.
func title(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

func fatalf(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "genpackets: "+format+"\n", args...)
	os.Exit(1)
}
