// Command genarmorattrs turns factual item armor modifier rows into Go data.
package main

import (
	"bufio"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"math"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

const input = "internal/server/testdata/vanilla-26.2/item_armor_attributes.tsv"
const output = "internal/server/itemarmorattr_gen.go"

type row struct{ item, attribute, key, slot, amount string }

func main() {
	reports := flag.String("reports", "", "optional item-component report directory; refresh factual TSV before generation")
	flag.Parse()
	if *reports != "" {
		extract(*reports)
	}
	data, err := os.ReadFile(input)
	if err != nil {
		panic(err)
	}
	var rows []row
	seen := map[string]bool{}
	scan := bufio.NewScanner(strings.NewReader(string(data)))
	for scan.Scan() {
		line := scan.Text()
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		f := strings.Split(line, "\t")
		if len(f) != 6 || f[5] != "add_value" {
			panic("invalid factual row: " + line)
		}
		if f[1] != "armor" && f[1] != "armor_toughness" && f[1] != "knockback_resistance" {
			panic("unexpected attribute: " + line)
		}
		switch f[3] {
		case "head", "chest", "legs", "feet", "body":
		default:
			panic("unexpected slot: " + line)
		}
		value, err := strconv.ParseFloat(f[4], 64)
		if err != nil || math.IsNaN(value) || math.IsInf(value, 0) {
			panic("invalid amount: " + line)
		}
		key := strings.Join(f[:4], "\t")
		if seen[key] {
			panic("duplicate modifier: " + line)
		}
		seen[key] = true
		rows = append(rows, row{f[0], f[1], f[2], f[3], f[4]})
	}
	if err := scan.Err(); err != nil {
		panic(err)
	}
	items := map[string]bool{}
	for _, r := range rows {
		items[r.item] = true
	}
	if len(rows) != 88 || len(items) != 41 {
		panic(fmt.Sprintf("want 41 items/88 rows, got %d/%d", len(items), len(rows)))
	}
	sort.Slice(rows, func(i, j int) bool {
		a, b := rows[i], rows[j]
		return a.item+"\t"+a.attribute+"\t"+a.key+"\t"+a.slot < b.item+"\t"+b.attribute+"\t"+b.key+"\t"+b.slot
	})
	var out strings.Builder
	fmt.Fprint(&out, "// Code generated by tools/genarmorattrs from Java 26.2 item component reports; DO NOT EDIT.\n\npackage server\n\n// All measured rows use add_value. Zero amounts remain real modifiers.\ntype itemArmorAttr struct {\n attribute, key, slot string\n value float64\n}\n\nvar itemArmorAttributes = map[string][]itemArmorAttr{\n")
	previous := ""
	for _, r := range rows {
		if r.item != previous {
			if previous != "" {
				fmt.Fprint(&out, "},\n")
			}
			fmt.Fprintf(&out, "%q: {\n", r.item)
			previous = r.item
		}
		fmt.Fprintf(&out, "{%q,%q,%q,%s},\n", r.attribute, r.key, r.slot, r.amount)
	}
	if previous != "" {
		fmt.Fprint(&out, "},\n")
	}
	fmt.Fprint(&out, "}\n")
	formatted, err := format.Source([]byte(out.String()))
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(output, formatted, 0644); err != nil {
		panic(err)
	}
}

func extract(directory string) {
	files, err := filepath.Glob(filepath.Join(directory, "*.json"))
	if err != nil || len(files) == 0 {
		panic("no item reports")
	}
	var lines []string
	for _, file := range files {
		data, err := os.ReadFile(file)
		if err != nil {
			panic(err)
		}
		var report struct {
			Components map[string]json.RawMessage `json:"components"`
		}
		if err := json.Unmarshal(data, &report); err != nil {
			panic(err)
		}
		var modifiers []struct {
			Attribute string      `json:"type"`
			Amount    json.Number `json:"amount"`
			Key       string      `json:"id"`
			Operation string      `json:"operation"`
			Slot      string      `json:"slot"`
		}
		if raw := report.Components["minecraft:attribute_modifiers"]; raw != nil {
			if err := json.Unmarshal(raw, &modifiers); err != nil {
				panic(err)
			}
		}
		for _, m := range modifiers {
			attribute := strings.TrimPrefix(m.Attribute, "minecraft:")
			if attribute != "armor" && attribute != "armor_toughness" && attribute != "knockback_resistance" {
				continue
			}
			item := strings.TrimSuffix(filepath.Base(file), ".json")
			lines = append(lines, strings.Join([]string{item, attribute, m.Key, m.Slot, m.Amount.String(), m.Operation}, "\t"))
		}
	}
	sort.Strings(lines)
	if err := os.WriteFile(input, []byte(strings.Join(lines, "\n")+"\n"), 0644); err != nil {
		panic(err)
	}
}
