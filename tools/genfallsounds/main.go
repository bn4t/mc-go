// Command genfallsounds turns the measured per-block fall-sound
// table into the maps mc-go ships.
//
// The measurement is in
// internal/server/testdata/vanilla-26.2/block_fall_sounds.tsv, one
// "block<TAB>sound<TAB>volume<TAB>pitch" line per vanilla block. It
// was extracted from the real 26.2 server jar: Blocks.<clinit>
// windows (BlockItemIds/BlockIds opener -> putstatic) carry the
// Properties.sound(SoundType) getstatic — or a ofFullCopy/ofLegacyCopy
// chain to another block's field, or a Properties-returning lambda
// resolved through the BootstrapMethods table — and each SoundType
// instance's <init> takes (volume, pitch, break, step, place, hit,
// fall) where the fifth SoundEvent is the fall sound.
//
// Usage (from the repo root):
//
//	go run ./tools/genfallsounds
package main

import (
	"bufio"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strconv"
	"strings"
)

const (
	tsvPath = "internal/server/testdata/vanilla-26.2/block_fall_sounds.tsv"
	outPath = "internal/server/blockfalls_gen.go"
)

func main() {
	f, err := os.Open(tsvPath)
	if err != nil {
		panic(err)
	}
	defer f.Close()

	type row struct {
		snd        string
		vol, pitch float64
	}
	rows := map[string]row{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		parts := strings.Split(line, "\t")
		if len(parts) != 4 {
			panic("bad row: " + line)
		}
		v, err := strconv.ParseFloat(parts[2], 64)
		if err != nil {
			panic("bad vol: " + line)
		}
		p, err := strconv.ParseFloat(parts[3], 64)
		if err != nil {
			panic("bad pitch: " + line)
		}
		rows[parts[0]] = row{snd: parts[1], vol: v, pitch: p}
	}
	if err := sc.Err(); err != nil {
		panic(err)
	}
	if len(rows) == 0 {
		panic("no rows parsed")
	}

	names := make([]string, 0, len(rows))
	for n := range rows {
		names = append(names, n)
	}
	sort.Strings(names)

	var b strings.Builder
	b.WriteString("// Code generated by tools/genfallsounds from\n")
	b.WriteString("// internal/server/testdata/vanilla-26.2/block_fall_sounds.tsv; DO NOT EDIT.\n\n")
	b.WriteString("package server\n\n")
	b.WriteString("// blockFallSoundNames maps each vanilla block name to the sound\n")
	b.WriteString("// event Entity.playBlockFallSound emits for it — the landed\n")
	b.WriteString("// block's SoundType.getFallSound.\n")
	b.WriteString("var blockFallSoundNames = map[string]string{\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q: %q,\n", n, rows[n].snd)
	}
	b.WriteString("}\n\n")
	b.WriteString("// blockFallSoundScale carries the SoundType (volume, pitch)\n")
	b.WriteString("// pair only where it differs from (1, 1); playBlockFallSound\n")
	b.WriteString("// multiplies by 0.5 / 0.75 on top.\n")
	b.WriteString("var blockFallSoundScale = map[string][2]float32{\n")
	for _, n := range names {
		r := rows[n]
		if r.vol != 1 || r.pitch != 1 {
			fmt.Fprintf(&b, "\t%q: {%v, %v},\n", n, r.vol, r.pitch)
		}
	}
	b.WriteString("}\n\n")
	b.WriteString("// blockFallSounds is blockFallSoundNames resolved to clientbound\n")
	b.WriteString("// registry ids through soundEventIDs.\n")
	b.WriteString("var blockFallSounds = func() map[string]int32 {\n")
	b.WriteString("\tm := make(map[string]int32, len(blockFallSoundNames))\n")
	b.WriteString("\tfor n, snd := range blockFallSoundNames {\n")
	b.WriteString("\t\tif id, ok := soundEventIDs[snd]; ok {\n")
	b.WriteString("\t\t\tm[n] = id\n")
	b.WriteString("\t\t}\n")
	b.WriteString("\t}\n")
	b.WriteString("\treturn m\n")
	b.WriteString("}()\n")

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(outPath, src, 0o644); err != nil {
		panic(err)
	}
	fmt.Printf("wrote %s (%d blocks)\n", outPath, len(rows))
}
