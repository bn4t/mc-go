// Command genattrs turns the measured per-entity attribute supplier
// table into the map mc-go ships.
//
// The measurement is in
// internal/server/testdata/vanilla-26.2/attr_suppliers.tsv, one
// "type<TAB>attr<TAB>base" line per supplier entry plus "#default"
// rows for each attribute's registered vanilla default. It was
// extracted from the real server jar's bytecode: DefaultAttributes'
// supplier map pairs each EntityType with its createAttributes
// factory, and the factories compose LivingEntity.createLivingAttributes
// with per-type add(Attributes.X, double) calls — so the TSV carries
// the exact bases vanilla instantiates per type.
//
// Usage (from the repo root):
//
//	go run ./tools/genattrs
package main

import (
	"bufio"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
)

const (
	tsvPath = "internal/server/testdata/vanilla-26.2/attr_suppliers.tsv"
	outPath = "internal/server/entityattr_gen.go"
)

func main() {
	f, err := os.Open(tsvPath)
	if err != nil {
		panic(err)
	}
	defer f.Close()

	defs := map[string]string{}
	byType := map[string]map[string]string{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := sc.Text()
		if line == "" {
			continue
		}
		parts := strings.Split(line, "\t")
		if len(parts) != 3 {
			panic("bad line: " + line)
		}
		if parts[0] == "#default" {
			defs[parts[1]] = parts[2]
			continue
		}
		if byType[parts[0]] == nil {
			byType[parts[0]] = map[string]string{}
		}
		byType[parts[0]][parts[1]] = parts[2]
	}
	if err := sc.Err(); err != nil {
		panic(err)
	}

	var b strings.Builder
	fmt.Fprint(&b, `// Code generated by tools/genattrs from
// internal/server/testdata/vanilla-26.2/attr_suppliers.tsv (extracted
// from the vanilla 26.2 jar's DefaultAttributes bytecode); DO NOT EDIT.

package server

// entityAttrBases is vanilla's per-entity-type attribute supplier:
// the set DefaultAttributes.getSupplier builds for each type — the
// shared living attributes inlined, then the type's own overrides.
// Only attributes listed are carried by that type's AttributeMap;
// the value is the supplier's base before any modifiers.
var entityAttrBases = map[string]map[string]float64{
`)
	types := make([]string, 0, len(byType))
	for t := range byType {
		types = append(types, t)
	}
	sort.Strings(types)
	for _, t := range types {
		fmt.Fprintf(&b, "\t%q: {\n", t)
		attrs := make([]string, 0, len(byType[t]))
		for a := range byType[t] {
			attrs = append(attrs, a)
		}
		sort.Strings(attrs)
		for _, a := range attrs {
			fmt.Fprintf(&b, "\t\t%q: %s,\n", a, byType[t][a])
		}
		fmt.Fprint(&b, "\t},\n")
	}
	fmt.Fprint(&b, "}\n\n// attrRegisteredDefaults is each attribute's vanilla registered\n")
	fmt.Fprint(&b, "// default value (Attributes' clinit) — what a one-argument\n// supplier add carries.\n")
	fmt.Fprint(&b, "var attrRegisteredDefaults = map[string]float64{\n")
	dattrs := make([]string, 0, len(defs))
	for a := range defs {
		dattrs = append(dattrs, a)
	}
	sort.Strings(dattrs)
	for _, a := range dattrs {
		fmt.Fprintf(&b, "\t%q: %s,\n", a, defs[a])
	}
	fmt.Fprint(&b, "}\n")

	out, err := format.Source([]byte(b.String()))
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(outPath, out, 0o644); err != nil {
		panic(err)
	}
	fmt.Printf("wrote %s: %d types, %d defaults\n", outPath, len(byType), len(defs))
}
