// genentitybounds projects numeric public getter facts into static type tables.
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"go/format"
	"math"
	"os"
	"sort"
	"strconv"
	"strings"
)

type facts struct {
	dims                 map[string][2]string
	passengers, vehicles map[string][3]string
	jar                  string
	negativeZero         bool
}

func main() {
	dims := flag.String("dimensions", "tools/gencommandeyes/public-dimensions.tsv", "public dimension fixture")
	attachments := flag.String("attachments", "tools/gencommandeyes/public-attachments.tsv", "public attachment fixture")
	out := flag.String("out", "internal/server/entitydimensions_generated.go", "generated tables")
	check := flag.Bool("check", false, "verify generated bytes")
	flag.Parse()
	if err := run(*dims, *attachments, *out, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
func jarHash(raw []byte) (string, error) {
	for _, line := range strings.Split(string(raw), "\n") {
		if h, ok := strings.CutPrefix(line, "# server-26.2.jar SHA256 "); ok {
			b, err := hex.DecodeString(h)
			if err != nil || len(b) != 32 {
				return "", fmt.Errorf("invalid version jar checksum")
			}
			return h, nil
		}
	}
	return "", fmt.Errorf("missing version jar checksum")
}
func number(text string, bits int, nonnegative bool) (string, bool, error) {
	f, err := strconv.ParseFloat(text, bits)
	if err != nil || math.IsNaN(f) || math.IsInf(f, 0) || math.Abs(f) > 1e6 || (nonnegative && f < 0) {
		return "", false, fmt.Errorf("invalid numeric getter %q", text)
	}
	if bits == 64 && f == 0 && math.Signbit(f) {
		return "math.Float64frombits(0x8000000000000000)", true, nil
	}
	return text, false, nil
}
func parse(dimensionRaw, attachmentRaw []byte) (facts, error) {
	f := facts{dims: map[string][2]string{}, passengers: map[string][3]string{}, vehicles: map[string][3]string{}}
	var err error
	f.jar, err = jarHash(dimensionRaw)
	if err != nil {
		return f, err
	}
	attachmentJar, err := jarHash(attachmentRaw)
	if err != nil || attachmentJar != f.jar {
		return f, fmt.Errorf("dimension and attachment jar checksums differ")
	}
	variants := map[string]bool{}
	scan := bufio.NewScanner(bytes.NewReader(dimensionRaw))
	for scan.Scan() {
		line := scan.Text()
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		a := strings.Split(line, "\t")
		if len(a) < 1 {
			return f, fmt.Errorf("empty dimension row")
		}
		start := 2
		switch a[0] {
		case "type":
			if len(a) != 5 {
				return f, fmt.Errorf("invalid type dimension row")
			}
			if _, ok := f.dims[a[1]]; ok {
				return f, fmt.Errorf("duplicate type %s", a[1])
			}
		case "variant":
			if len(a) != 6 {
				return f, fmt.Errorf("invalid variant dimension row")
			}
			key := a[1] + "/" + a[2]
			if variants[key] {
				return f, fmt.Errorf("duplicate variant %s", key)
			}
			variants[key] = true
			start = 3
		default:
			return f, fmt.Errorf("unknown dimension row %q", a[0])
		}
		for _, v := range a[start:] {
			if _, _, err := number(v, 32, true); err != nil {
				return f, err
			}
		}
		if a[0] == "type" {
			f.dims[a[1]] = [2]string{a[2], a[3]}
		}
	}
	if err := scan.Err(); err != nil {
		return f, err
	}
	if len(f.dims) != 158 || len(variants) != 44 {
		return f, fmt.Errorf("incomplete dimensions: %d types %d variants", len(f.dims), len(variants))
	}
	scan = bufio.NewScanner(bytes.NewReader(attachmentRaw))
	for scan.Scan() {
		line := scan.Text()
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		a := strings.Split(line, "\t")
		if len(a) != 8 || a[0] != "type" {
			return f, fmt.Errorf("invalid attachment row")
		}
		if _, ok := f.dims[a[1]]; !ok {
			return f, fmt.Errorf("unknown attachment type %s", a[1])
		}
		if _, ok := f.passengers[a[1]]; ok {
			return f, fmt.Errorf("duplicate attachment type %s", a[1])
		}
		var values [6]string
		for i, v := range a[2:] {
			value, neg, err := number(v, 64, false)
			if err != nil {
				return f, err
			}
			values[i] = value
			f.negativeZero = f.negativeZero || neg
		}
		f.passengers[a[1]] = [3]string{values[0], values[1], values[2]}
		f.vehicles[a[1]] = [3]string{values[3], values[4], values[5]}
	}
	if err := scan.Err(); err != nil {
		return f, err
	}
	if len(f.passengers) != 158 {
		return f, fmt.Errorf("incomplete attachment census: %d", len(f.passengers))
	}
	return f, nil
}
func generate(dimensionRaw, attachmentRaw []byte) ([]byte, error) {
	f, err := parse(dimensionRaw, attachmentRaw)
	if err != nil {
		return nil, err
	}
	names := make([]string, 0, len(f.dims))
	for name := range f.dims {
		names = append(names, name)
	}
	sort.Strings(names)
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by go run ./tools/genentitybounds; DO NOT EDIT.\n// Version jar SHA256: %s\n// Dimension input SHA256: %x\n// Attachment input SHA256: %x\n// Public EntityType dimension records and first unrotated attachment points.\n// Instance pose, size, scale and vehicle-class overrides remain separate.\npackage server\n\n", f.jar, sha256.Sum256(dimensionRaw), sha256.Sum256(attachmentRaw))
	if f.negativeZero {
		b.WriteString("import \"math\"\n\n")
	}
	b.WriteString("var entityTypeBaseDims = map[string][2]float32{\n")
	for _, name := range names {
		v := f.dims[name]
		fmt.Fprintf(&b, "%q: {%s,%s},\n", name, v[0], v[1])
	}
	b.WriteString("}\n")
	for _, table := range []struct {
		name   string
		values map[string][3]string
	}{{"entityTypePassengerAttachments", f.passengers}, {"entityTypeVehicleAttachments", f.vehicles}} {
		fmt.Fprintf(&b, "var %s = map[string][3]float64{\n", table.name)
		for _, name := range names {
			v := table.values[name]
			fmt.Fprintf(&b, "%q: {%s,%s,%s},\n", name, v[0], v[1], v[2])
		}
		b.WriteString("}\n")
	}
	return format.Source(b.Bytes())
}
func run(dimensionPath, attachmentPath, output string, check bool) error {
	dims, err := os.ReadFile(dimensionPath)
	if err != nil {
		return err
	}
	attachments, err := os.ReadFile(attachmentPath)
	if err != nil {
		return err
	}
	generated, err := generate(dims, attachments)
	if err != nil {
		return err
	}
	if check {
		old, err := os.ReadFile(output)
		if err != nil {
			return err
		}
		if !bytes.Equal(old, generated) {
			return fmt.Errorf("%s differs from getter facts", output)
		}
		return nil
	}
	return os.WriteFile(output, generated, 0644)
}
