// Command genregistries regenerates the official registry tables used
// by mc-go from the reports emitted by the vanilla server's built-in
// data generator (java -DbundlerMainClass=net.minecraft.data.Main
// -jar server.jar --reports). Reports are data, not code: they are the
// same values the client and server hardcode, so generated tables are
// exact by construction.
//
// Usage (from the repo root):
//
//	go run ./tools/genregistries
package main

import (
	"encoding/base64"
	"encoding/binary"
	"encoding/json"
	"fmt"
	"math/bits"
	"os"
	"sort"
	"strings"
)

func main() {
	blocks := readJSON("vanilla/reports/blocks.json")
	registries := readJSON("vanilla/reports/registries.json")

	writeWorldBlocks(blocks)
	writeWorldBlockStates(blocks)
	writeWorldItems(registries)
	writeEntityTypes(registries)
	writeLootFunctions(registries)
	writeWear()
	fmt.Println("generated:")
	fmt.Println("  internal/world/blocks_gen.go")
	fmt.Println("  internal/world/blockstates_gen.go")
	fmt.Println("  internal/world/items_gen.go")
	fmt.Println("  internal/server/entitytypes_gen.go")
	fmt.Println("  internal/server/lootfunctions_gen.go")
	fmt.Println("  internal/server/wear_gen.go")
}

func readJSON(path string) map[string]any {
	raw, err := os.ReadFile(path)
	if err != nil {
		fatalf("read %s: %v (run the data generator first; see tool comment)", path, err)
	}
	var v map[string]any
	if err := json.Unmarshal(raw, &v); err != nil {
		fatalf("parse %s: %v", path, err)
	}
	return v
}

// blockStates extracts block name -> default state id and the highest
// state id from blocks.json.
func blockStates(blocks map[string]any) (map[string]int, int) {
	out := make(map[string]int, len(blocks))
	max := -1
	for name, raw := range blocks {
		blk, ok := raw.(map[string]any)
		if !ok {
			continue
		}
		states, _ := blk["states"].([]any)
		for _, sraw := range states {
			st, _ := sraw.(map[string]any)
			id := int(st["id"].(float64))
			if id > max {
				max = id
			}
			if def, _ := st["default"].(bool); def {
				out[strings.TrimPrefix(name, "minecraft:")] = id
			}
		}
	}
	return out, max
}

// paletteConsts are the blocks mc-go's generator names in code.
var paletteConsts = []struct{ goName, block string }{
	{"Air", "air"},
	{"Stone", "stone"},
	{"Dirt", "dirt"},
	{"Grass", "grass_block"},
}

func writeWorldBlocks(blocks map[string]any) {
	states, max := blockStates(blocks)
	var b strings.Builder
	b.WriteString("// Code generated by tools/genregistries from vanilla/reports/blocks.json; DO NOT EDIT.\n\n")
	b.WriteString("package world\n\nimport \"sort\"\n\n")
	b.WriteString("// maxBlockState is the highest global block-state id, plus one.\n")
	fmt.Fprintf(&b, "const maxBlockState = %d\n\n", max+1)
	b.WriteString("// Common block-state ids, generated from the official report.\n")
	b.WriteString("const (\n")
	for _, p := range paletteConsts {
		id, ok := states[p.block]
		if !ok {
			fatalf("palette block %s missing from blocks.json", p.block)
		}
		fmt.Fprintf(&b, "\t%s Block = %d\n", p.goName, id)
	}
	b.WriteString(")\n\n")
	b.WriteString("// blockStates maps block name (without the minecraft: prefix)\n")
	b.WriteString("// to its default block-state id.\n")
	b.WriteString("var blockStates = map[string]Block{\n")
	writeSorted(&b, states, func(v int) string { return fmt.Sprintf("%d", v) })
	b.WriteString("}\n\n")
	b.WriteString("// BlockState returns the default state id for a block name\n")
	b.WriteString("// (without the minecraft: prefix).\n")
	b.WriteString("func BlockState(name string) (Block, bool) {\n")
	b.WriteString("\ts, ok := blockStates[name]\n")
	b.WriteString("\treturn s, ok\n")
	b.WriteString("}\n\n")
	b.WriteString("// blockNames maps a block's default state id back to its name, one\n")
	b.WriteString("// entry per block. It exists to list the name universe; resolving an\n")
	b.WriteString("// arbitrary state id is StateOwner's job, because a chunk palette\n")
	b.WriteString("// carries every state and not just the defaults.\n")
	b.WriteString("var blockNames = map[Block]string{\n")
	names := make([]string, 0, len(states))
	for n := range states {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		fmt.Fprintf(&b, "\t%d: %q,\n", states[n], n)
	}
	b.WriteString("}\n\n")
	b.WriteString("// BlockNames lists every block name, sorted. The command\n")
	b.WriteString("// completion engine and /setblock use it as the name universe.\n")
	b.WriteString("func BlockNames() []string {\n")
	b.WriteString("\tout := make([]string, 0, len(blockNames))\n")
	b.WriteString("\tfor _, name := range blockNames {\n")
	b.WriteString("\t\tout = append(out, name)\n")
	b.WriteString("\t}\n")
	b.WriteString("\tsort.Strings(out)\n")
	b.WriteString("\treturn out\n")
	b.WriteString("}\n")
	writeFile("internal/world/blocks_gen.go", b.String())
	blockDefault = states
}

