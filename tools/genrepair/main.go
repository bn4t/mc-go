// Command genrepair turns the official item-component reports into the
// anvil repair-material table mc-go ships.
//
// The data is the vanilla server's own data generator output: every
// item's minecraft:repairable component names the item or item tag its
// anvil repair consumes (vanilla/reports/minecraft/components/item/),
// and the tags resolve through the generated data pack's item tags
// (vanilla/generated/data/minecraft/tags/item/). Reports are data, not
// code: they are the same values the real server loads, so the
// generated table is exact by construction.
//
// Usage (from the repo root):
//
//	go run ./tools/genrepair
package main

import (
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const (
	componentsDir = "vanilla/reports/minecraft/components/item"
	tagsDir       = "vanilla/generated/data/minecraft/tags/item"
	outPath       = "internal/server/repairmaterials_gen.go"
)

func main() {
	repairs := map[string][]string{}
	err := filepath.WalkDir(componentsDir, func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(path, ".json") {
			return err
		}
		var doc struct {
			Components map[string]json.RawMessage `json:"components"`
		}
		raw, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if err := json.Unmarshal(raw, &doc); err != nil {
			return fmt.Errorf("%s: %v", path, err)
		}
		var rep struct {
			Items string `json:"items"`
		}
		raw, ok := doc.Components["minecraft:repairable"]
		if !ok {
			return nil
		}
		if err := json.Unmarshal(raw, &rep); err != nil {
			return fmt.Errorf("%s: repairable: %v", path, err)
		}
		name := strings.TrimSuffix(filepath.Base(path), ".json")
		var materials []string
		if strings.HasPrefix(rep.Items, "#") {
			materials = resolveTag(strings.TrimPrefix(rep.Items, "#minecraft:"), map[string]bool{})
		} else {
			materials = []string{rep.Items}
		}
		for i, m := range materials {
			materials[i] = strings.TrimPrefix(m, "minecraft:")
		}
		sort.Strings(materials)
		repairs[name] = materials
		return nil
	})
	if err != nil {
		fatalf("walk %s: %v", componentsDir, err)
	}
	if len(repairs) == 0 {
		fatalf("no repairable items under %s", componentsDir)
	}

	var b strings.Builder
	fmt.Fprint(&b, `// Code generated by tools/genrepair from the vanilla reports'
// minecraft:repairable components and the generated data pack's item
// tags; DO NOT EDIT.

package server

// repairMaterials maps every repairable item to the material items its
// anvil repair consumes, sorted. The values come from each item's
// minecraft:repairable component (a direct item or an item tag the
// generator resolved through the data pack), the same data the real
// server loads.
var repairMaterials = map[string][]string{
`)
	var names []string
	for name := range repairs {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		fmt.Fprintf(&b, "\t%q: {", name)
		for i, m := range repairs[name] {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%q", m)
		}
		b.WriteString("},\n")
	}
	fmt.Fprint(&b, `}

// repairMaterialOf reports whether the sacrifice repairs the target on
// an anvil, by the target's repairable component. Item names are
// registry names without the minecraft: prefix, matching
// itemNameOf's returns.
func repairMaterialOf(target, sacrifice ItemStack) bool {
	tname, ok := itemNameOf(target.ID)
	if !ok {
		return false
	}
	sname, ok := itemNameOf(sacrifice.ID)
	if !ok {
		return false
	}
	for _, m := range repairMaterials[tname] {
		if m == sname {
			return true
		}
	}
	return false
}
`)

	body, err := format.Source([]byte(b.String()))
	if err != nil {
		fatalf("generated source does not parse: %v", err)
	}
	if err := os.WriteFile(outPath, body, 0o644); err != nil {
		fatalf("write %s: %v", outPath, err)
	}
	fmt.Printf("generated %s: %d repairable items\n", outPath, len(repairs))
}

// resolveTag expands one item tag through the generated data pack's tag
// files, following nested #tag references.
func resolveTag(tag string, seen map[string]bool) []string {
	short := strings.TrimPrefix(tag, "minecraft:")
	if seen[short] {
		fatalf("item tag %s recurses", tag)
	}
	seen[short] = true
	raw, err := os.ReadFile(filepath.Join(tagsDir, short+".json"))
	if err != nil {
		fatalf("item tag %s: %v", tag, err)
	}
	var doc struct {
		Values []string `json:"values"`
	}
	if err := json.Unmarshal(raw, &doc); err != nil {
		fatalf("item tag %s: %v", tag, err)
	}
	var out []string
	for _, v := range doc.Values {
		if strings.HasPrefix(v, "#") {
			out = append(out, resolveTag(strings.TrimPrefix(v, "#"), seen)...)
		} else {
			out = append(out, v)
		}
	}
	return out
}

func fatalf(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "genrepair: "+format+"\n", args...)
	os.Exit(1)
}
