// Command genrarity turns the official item-component reports into the
// item rarity table mc-go ships.
//
// The data is the vanilla server's own data generator output: every
// item's minecraft:rarity component names its base rarity
// (vanilla/reports/minecraft/components/item/). Reports are data, not
// code: they are the same values the real server loads, so the
// generated table is exact by construction.
//
// Usage (from the repo root):
//
//	go run ./tools/genrarity
package main

import (
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const (
	componentsDir = "vanilla/reports/minecraft/components/item"
	outPath       = "internal/server/itemrarity_gen.go"
)

type itemComponents struct {
	Components map[string]json.RawMessage `json:"components"`
}

func main() {
	ents, err := os.ReadDir(componentsDir)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	// rarity maps an item's short name to its rarity: anything without
	// an explicit component is common — the enum's default.
	rarity := map[string]string{}
	for _, ent := range ents {
		if !strings.HasSuffix(ent.Name(), ".json") {
			continue
		}
		data, err := os.ReadFile(filepath.Join(componentsDir, ent.Name()))
		if err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		var ic itemComponents
		if err := json.Unmarshal(data, &ic); err != nil {
			fmt.Fprintf(os.Stderr, "%s: %v\n", ent.Name(), err)
			os.Exit(1)
		}
		raw, ok := ic.Components["minecraft:rarity"]
		if !ok {
			continue
		}
		var r string
		if err := json.Unmarshal(raw, &r); err != nil {
			fmt.Fprintf(os.Stderr, "%s rarity: %v\n", ent.Name(), err)
			os.Exit(1)
		}
		name := strings.TrimSuffix(strings.TrimPrefix(ent.Name(), "minecraft_"), ".json")
		if r != "common" {
			rarity[name] = r
		}
	}

	names := make([]string, 0, len(rarity))
	for n := range rarity {
		names = append(names, n)
	}
	sort.Strings(names)

	var b strings.Builder
	b.WriteString("// Code generated by tools/genrarity from vanilla/reports/minecraft/components/item; DO NOT EDIT.\n\n")
	b.WriteString("package server\n\n")
	b.WriteString("// itemRarity is every item's base minecraft:rarity component —\n")
	b.WriteString("// anything absent is common. The effective rarity bumps one step\n")
	b.WriteString("// (common/uncommon -> rare, rare -> epic) while enchanted.\n")
	b.WriteString("var itemRarity = map[string]string{\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q: %q,\n", n, rarity[n])
	}
	b.WriteString("}\n")

	out, err := format.Source([]byte(b.String()))
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(outPath, out, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Printf("genrarity: %d non-common items -> %s\n", len(names), outPath)
}
