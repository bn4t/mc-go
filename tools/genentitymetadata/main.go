// Command genentitymetadata measures factual entity metadata accessors by runtime
// reflection against local official server distributions. It does not decompile
// or translate methods. Regeneration needs JDK 25 and unpacked server libraries.
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

type field struct {
	name              string
	index, serializer int
}
type facts struct {
	packets                  map[string]string
	enums                    map[int]map[int]string
	fields                   map[string][]field
	serializers              map[int]string
	poses                    map[int]string
	jarHash, measurementHash string
}

func main() {
	jdk := flag.String("jdk", "", "directory containing java and javac, otherwise PATH")
	root := flag.String("root", ".", "repository root")
	flag.Parse()
	probe := filepath.Join(*root, "tools/genentitymetadata/MetadataProbe.java")
	temp, err := os.MkdirTemp("", "mcgo-entity-metadata-")
	must(err)
	defer os.RemoveAll(temp)
	measured := map[int]facts{}
	for protocol, version := range map[int]string{775: "26.1", 776: "26.2"} {
		base := filepath.Join(*root, "vanilla", "measure-"+version)
		jar := filepath.Join(base, "versions", version, "server-"+version+".jar")
		classpath := []string{jar}
		must(filepath.WalkDir(filepath.Join(base, "libraries"), func(path string, d os.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if !d.IsDir() && strings.HasSuffix(path, ".jar") {
				classpath = append(classpath, path)
			}
			return nil
		}))
		sort.Strings(classpath[1:])
		classes := filepath.Join(temp, version)
		must(os.Mkdir(classes, 0755))
		run(filepath.Join(*jdk, "javac"), "-cp", strings.Join(classpath, string(os.PathListSeparator)), "-d", classes, probe, filepath.Join(*root, "tools/genentitymetadata/CodecProbe.java"))
		out := filepath.Join(temp, version+".tsv")
		run(filepath.Join(*jdk, "java"), "-cp", classes+string(os.PathListSeparator)+strings.Join(classpath, string(os.PathListSeparator)), "MetadataProbe", out)
		run(filepath.Join(*jdk, "java"), "-cp", classes+string(os.PathListSeparator)+strings.Join(classpath, string(os.PathListSeparator)), "CodecProbe", out+".codecs")
		codecRaw, err := os.ReadFile(out + ".codecs")
		must(err)
		raw, err := os.ReadFile(out)
		must(err)
		f := parse(append(raw, codecRaw...))
		f.jarHash = hashFile(jar)
		f.measurementHash = fmt.Sprintf("%x", sha256.Sum256(raw))
		measured[protocol] = f
	}
	old, current := measured[775], measured[776]
	if len(old.enums) != len(current.enums) {
		fatal("metadata enum serializer set changed")
	}
	for id, values := range current.enums {
		if !equalNamedIDs(old.enums[id], values) {
			fatal("metadata enum values changed for serializer %d", id)
		}
	}
	if !equalNamedIDs(old.serializers, current.serializers) || !equalNamedIDs(old.poses, current.poses) {
		fatal("serializer or pose identifiers changed; extend the versioned value codec before regenerating")
	}
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by tools/genentitymetadata using runtime reflection; DO NOT EDIT.")
	fmt.Fprintf(&out, "// JAR SHA256: 775 %s; 776 %s.\n", old.jarHash, current.jarHash)
	fmt.Fprintln(&out, "// Accessor fields, serializer IDs, and pose ordinals are measured facts, not copied method implementations.")
	fmt.Fprintln(&out, "package server")
	fmt.Fprintln(&out, "var javaMetadataSerializers = [...]string{")
	for id := 0; id < len(current.serializers); id++ {
		fmt.Fprintf(&out, "%q,\n", current.serializers[id])
	}
	fmt.Fprintln(&out, "}")
	fmt.Fprintln(&out, "var javaMetadataPoses = [...]string{")
	for id := 0; id < len(current.poses); id++ {
		fmt.Fprintf(&out, "%q,\n", current.poses[id])
	}
	fmt.Fprintln(&out, "}")
	fmt.Fprintln(&out, "var javaMetadataEnums = map[int32][]string{")
	for id := 0; id < len(current.serializers); id++ {
		if values, ok := current.enums[id]; ok {
			fmt.Fprintf(&out, "%d: {", id)
			for i := 0; i < len(values); i++ {
				fmt.Fprintf(&out, "%q,", values[i])
			}
			fmt.Fprintln(&out, "},")
		}
	}
	fmt.Fprintln(&out, "}")
	fmt.Fprintln(&out, "var javaMetadataSchema776 = map[string][]javaMetadataField{")
	for _, name := range sortedKeys(current.fields) {
		fields := current.fields[name]
		sort.Slice(fields, func(i, j int) bool { return fields[i].index < fields[j].index })
		fmt.Fprintf(&out, "%q: {\n", name)
		for _, f := range fields {
			fmt.Fprintf(&out, "{%d,%d,%q},\n", f.index, f.serializer, f.name)
		}
		fmt.Fprintln(&out, "},")
	}
	fmt.Fprintln(&out, "}")
	fmt.Fprintln(&out, "// Missing fields are explicitly omitted only where the measured 775 entity has no corresponding accessor.")
	fmt.Fprintln(&out, "var javaMetadataIndices775 = map[string]map[byte]int16{")
	deltaCount := 0
	for _, name := range sortedKeys(current.fields) {
		target, ok := old.fields[name]
		if !ok {
			continue
		}
		byName := map[string]field{}
		for _, f := range target {
			byName[f.name] = f
		}
		var deltas []string
		for _, f := range current.fields[name] {
			mapped, ok := byName[f.name]
			if !ok {
				// Absence is a fact; omission is a separate reviewed policy.
				// A future metadata addition must not silently acquire one.
				if (name != "minecraft:slime" && name != "minecraft:magma_cube") || (f.name != "DATA_BABY_ID" && f.name != "AGE_LOCKED") {
					fatal("missing accessor %s/%s requires an explicit compatibility policy", name, f.name)
				}
				deltas = append(deltas, fmt.Sprintf("%d:-1,", f.index))
				continue
			}
			if mapped.serializer != f.serializer {
				fatal("metadata serializer changed for %s/%s", name, f.name)
			}
			if mapped.index != f.index {
				deltas = append(deltas, fmt.Sprintf("%d:%d,", f.index, mapped.index))
			}
			delete(byName, f.name)
		}
		if len(byName) != 0 {
			fatal("target-only metadata fields for %s need explicit versioned construction", name)
		}
		if len(deltas) > 0 {
			fmt.Fprintf(&out, "%q: {%s},\n", name, strings.Join(deltas, ""))
			deltaCount += len(deltas)
		}
	}
	fmt.Fprintln(&out, "}")
	formatted, err := format.Source(out.Bytes())
	must(err)
	must(os.WriteFile(filepath.Join(*root, "internal/server/java_metadata_schema_gen.go"), formatted, 0644))
	jdkVersion := run(filepath.Join(*jdk, "java"), "-version")
	manifest := map[string]any{"source_class": "runtime reflection of official server static EntityDataAccessor fields", "tool": "tools/genentitymetadata", "jdk": strings.TrimSpace(string(jdkVersion)), "probe_sha256": hashFile(probe), "codec_probe_sha256": hashFile(filepath.Join(*root, "tools/genentitymetadata/CodecProbe.java")), "775_jar_sha256": old.jarHash, "776_jar_sha256": current.jarHash, "775_measurement_sha256": old.measurementHash, "776_measurement_sha256": current.measurementHash, "775_entity_schemas": len(old.fields), "776_entity_schemas": len(current.fields), "serializer_count": len(current.serializers), "pose_count": len(current.poses), "shared_entity_accessor_deltas": deltaCount}
	encoded, err := json.MarshalIndent(manifest, "", "  ")
	must(err)
	encoded = append(encoded, '\n')
	must(os.WriteFile(filepath.Join(*root, "internal/server/testdata/java-entity-metadata-measurement.json"), encoded, 0644))
	fixtures := map[string]any{"source_class": "official public codec invocation with independently selected values", "generator": "tools/genentitymetadata", "775": old.packets, "776": current.packets}
	encoded, err = json.MarshalIndent(fixtures, "", "  ")
	must(err)
	encoded = append(encoded, '\n')
	must(os.WriteFile(filepath.Join(*root, "internal/server/testdata/java-entity-wire-codecs.json"), encoded, 0644))
	fmt.Printf("measured %d/%d entity schemas, %d serializers, %d poses, %d shared accessor deltas\n", len(old.fields), len(current.fields), len(current.serializers), len(current.poses), deltaCount)
}

func parse(raw []byte) facts {
	f := facts{packets: map[string]string{}, enums: map[int]map[int]string{}, fields: map[string][]field{}, serializers: map[int]string{}, poses: map[int]string{}}
	scan := bufio.NewScanner(bytes.NewReader(raw))
	for scan.Scan() {
		parts := strings.Split(scan.Text(), "\t")
		switch parts[0] {
		case "serializer", "pose":
			if len(parts) != 3 {
				fatal("malformed measurement: %s", scan.Text())
			}
			id := number(parts[2])
			m := f.serializers
			if parts[0] == "pose" {
				m = f.poses
			}
			if _, ok := m[id]; ok {
				fatal("duplicate measured ID")
			}
			m[id] = parts[1]
		case "packet":
			if len(parts) != 3 {
				fatal("malformed packet fixture")
			}
			f.packets[parts[1]] = parts[2]
		case "enum":
			if len(parts) != 4 {
				fatal("malformed enum value")
			}
			id, value := number(parts[1]), number(parts[3])
			if f.enums[id] == nil {
				f.enums[id] = map[int]string{}
			}
			if _, ok := f.enums[id][value]; ok {
				fatal("duplicate enum value")
			}
			f.enums[id][value] = parts[2]
		case "entity":
			if len(parts) != 4 {
				fatal("malformed entity")
			}
			f.fields[parts[1]] = nil
		case "field":
			if len(parts) != 6 {
				fatal("malformed field")
			}
			_, name, ok := strings.Cut(parts[2], "#")
			if !ok {
				fatal("malformed field identity")
			}
			index, serializer := number(parts[3]), number(parts[5])
			if index < 0 || index >= 255 || f.serializers[serializer] != parts[4] {
				fatal("invalid accessor")
			}
			for _, prior := range f.fields[parts[1]] {
				if prior.name == name || prior.index == index {
					fatal("duplicate entity field %s/%s", parts[1], name)
				}
			}
			f.fields[parts[1]] = append(f.fields[parts[1]], field{name, index, serializer})
		default:
			fatal("unknown measurement record")
		}
	}
	must(scan.Err())
	return f
}
func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
func equalNamedIDs(a, b map[int]string) bool {
	if len(a) != len(b) {
		return false
	}
	for k, v := range a {
		if b[k] != v {
			return false
		}
	}
	return true
}
func number(s string) int { n, err := strconv.Atoi(s); must(err); return n }
func hashFile(path string) string {
	raw, err := os.ReadFile(path)
	must(err)
	return fmt.Sprintf("%x", sha256.Sum256(raw))
}
func run(command string, args ...string) []byte {
	out, err := exec.Command(command, args...).CombinedOutput()
	if err != nil {
		fatal("%s: %v\n%s", command, err, out)
	}
	return out
}
func must(err error) {
	if err != nil {
		fatal("%v", err)
	}
}
func fatal(message string, args ...any) { fmt.Fprintf(os.Stderr, message+"\n", args...); os.Exit(1) }
