// Command genmobambient turns the measured per-type ambient-voice
// table into the map mc-go ships.
//
// The measurement is in
// internal/server/testdata/vanilla-26.2/ambient_sounds.tsv, one
// "type<TAB>sound<TAB>interval<TAB>volume" line per vocal mob type.
// It was extracted from the real 26.2 server jar: each Mob subclass's
// getAmbientSound / getAmbientSoundInterval / getSoundVolume bytecode
// (SoundEvents fields resolved through SoundEvents.<clinit>'s
// ldc+putstatic pairs, intervals and volumes walked up the superclass
// chain), plus the sound-variant datapack jsons for pig/chicken/cow/
// cat/wolf whose voices moved to *SoundVariant registries in 26.x.
//
// Usage (from the repo root):
//
//	go run ./tools/genmobambient
package main

import (
	"bufio"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"

	"mc-go/internal/server"
)

const (
	tsvPath = "internal/server/testdata/vanilla-26.2/ambient_sounds.tsv"
	outPath = "internal/server/mobambient_gen.go"
)

func main() {
	f, err := os.Open(tsvPath)
	if err != nil {
		panic(err)
	}
	defer f.Close()

	type row struct {
		snd      string
		babySnd  string
		interval string
		vol      string
	}
	rows := map[string]row{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		parts := strings.Split(line, "\t")
		if len(parts) != 5 {
			panic("bad row: " + line)
		}
		rows[parts[0]] = row{snd: parts[1], babySnd: parts[2], interval: parts[3], vol: parts[4]}
	}
	if err := sc.Err(); err != nil {
		panic(err)
	}

	var b strings.Builder
	b.WriteString(`// Code generated by tools/genmobambient; DO NOT EDIT.

package server

// mobAmbient is the per-type ambient voice measured from vanilla
// 26.2's Mob subclasses: the getAmbientSound sound id, the
// getAmbientSoundInterval gate (ambientSoundTime resets to -interval
// after a voice, then random.nextInt(1000) < ++time fires), and the
// getSoundVolume at which it plays. Animal lines inherit interval 120,
// horses 400/0.8, ocelot 900, guardian 160, turtle 200.
var mobAmbient = map[string]struct {
	snd      int32
	babySnd  int32
	interval int32
	vol      float32
}{
`)
	var names []string
	for n := range rows {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		r := rows[n]
		sid, ok := soundEventID(r.snd)
		if !ok {
			panic("unknown sound: " + r.snd)
		}
		var bid int32
		if r.babySnd != "-" {
			bid, ok = soundEventID(r.babySnd)
			if !ok {
				panic("unknown sound: " + r.babySnd)
			}
		}
		fmt.Fprintf(&b, "\t%q: {%d, %d, %s, %s}, // %s\n", n, sid, bid, r.interval, r.vol, r.snd)
	}
	b.WriteString("}\n")

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(outPath, src, 0o644); err != nil {
		panic(err)
	}
	fmt.Printf("wrote %s: %d types\n", outPath, len(rows))
}

// soundEventID resolves the registry name through the generated table.
func soundEventID(name string) (int32, bool) {
	return server.SoundEventID(name)
}
