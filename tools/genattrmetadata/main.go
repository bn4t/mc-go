// Command genattrmetadata generates factual attribute registry metadata.
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"math"
	"os"
	"sort"
	"strconv"
	"strings"
)

const input = "internal/server/testdata/vanilla-26.2/attribute_metadata.tsv"
const output = "internal/server/attributeinfo_gen.go"

func main() {
	data, err := os.ReadFile(input)
	if err != nil {
		panic(err)
	}
	rows := map[string][]string{}
	scan := bufio.NewScanner(bytes.NewReader(data))
	for scan.Scan() {
		line := scan.Text()
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Split(line, "\t")
		if len(fields) != 5 || !strings.HasPrefix(fields[0], "minecraft:") {
			panic("invalid metadata row: " + line)
		}
		name := strings.TrimPrefix(fields[0], "minecraft:")
		if _, exists := rows[name]; exists {
			panic("duplicate attribute: " + name)
		}
		values := [3]float64{}
		for i := range values {
			v, e := strconv.ParseFloat(fields[i+1], 64)
			if e != nil || math.IsNaN(v) || math.IsInf(v, 0) {
				panic("invalid attribute number: " + line)
			}
			values[i] = v
		}
		if values[1] > values[0] || values[0] > values[2] {
			panic("default outside range: " + line)
		}
		if fields[4] != "true" && fields[4] != "false" {
			panic("invalid sync flag: " + line)
		}
		rows[name] = fields
	}
	if err := scan.Err(); err != nil {
		panic(err)
	}
	if len(rows) != 40 {
		panic(fmt.Sprintf("want 40 attributes, got %d", len(rows)))
	}
	names := make([]string, 0, len(rows))
	for name := range rows {
		names = append(names, name)
	}
	sort.Strings(names)
	var out strings.Builder
	fmt.Fprint(&out, "// Code generated by tools/genattrmetadata from the Java 26.2 public registry getters; DO NOT EDIT.\n\npackage server\n\n// attributeInfo records registered defaults, ranged bounds and client sync policy.\n// Entity suppliers may override the registered default.\nvar attributeInfo = map[string]struct {\n defaultValue, minValue, maxValue float64\n clientSync bool\n}{\n")
	for _, name := range names {
		f := rows[name]
		fmt.Fprintf(&out, "%q: {%s, %s, %s, %s},\n", name, f[1], f[2], f[3], f[4])
	}
	fmt.Fprint(&out, "}\n")
	formatted, err := format.Source([]byte(out.String()))
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(output, formatted, 0644); err != nil {
		panic(err)
	}
}
