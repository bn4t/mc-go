// Command genjavawiredomains records names and numeric IDs from official
// registry reports. Shapes and payload codecs require separate measurement.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"runtime"
	"sort"
)

type registryReport map[string]struct {
	Entries map[string]struct {
		ID int32 `json:"protocol_id"`
	} `json:"entries"`
}

type report struct {
	domains map[string][]string
	hash    string
}

func load(path string) (report, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return report{}, err
	}
	var doc registryReport
	if err := json.Unmarshal(raw, &doc); err != nil {
		return report{}, err
	}
	r := report{domains: make(map[string][]string), hash: fmt.Sprintf("%x", sha256.Sum256(raw))}
	for key, domain := range doc {
		names := make([]string, len(domain.Entries))
		for name, entry := range domain.Entries {
			if entry.ID < 0 || int(entry.ID) >= len(names) || names[entry.ID] != "" {
				return report{}, fmt.Errorf("%s: duplicate/non-contiguous ID %d", key, entry.ID)
			}
			names[entry.ID] = name
		}
		for id, name := range names {
			if name == "" {
				return report{}, fmt.Errorf("%s: missing ID %d", key, id)
			}
		}
		r.domains[key] = names
	}
	return r, nil
}

func run() error {
	source := flag.String("source", "vanilla/measure-26.1/generated/reports/registries.json", "official protocol 775 registry report")
	target := flag.String("target", "vanilla/measure-26.2/generated/reports/registries.json", "official protocol 776 registry report")
	output := flag.String("output", "internal/server/java_wire_domains_gen.go", "generated Go facts")
	flag.Parse()
	a, err := load(*source)
	if err != nil {
		return err
	}
	b, err := load(*target)
	if err != nil {
		return err
	}
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by tools/genjavawiredomains; DO NOT EDIT.")
	fmt.Fprintln(&out, "// Source class: official generated registry reports (numeric facts only).")
	fmt.Fprintf(&out, "// Tool: %s; source protocol 775 SHA-256: %s\n", runtime.Version(), a.hash)
	fmt.Fprintf(&out, "// Target protocol 776 SHA-256: %s\n", b.hash)
	fmt.Fprintln(&out, "\npackage server")
	fmt.Fprintln(&out, "\nvar javaBuiltinRegistryFacts = map[int32]map[string][]string{")
	for _, entry := range []struct {
		protocol int
		data     report
	}{{775, a}, {776, b}} {
		fmt.Fprintf(&out, "\t%d: {\n", entry.protocol)
		keys := make([]string, 0, len(entry.data.domains))
		for key := range entry.data.domains {
			keys = append(keys, key)
		}
		sort.Strings(keys)
		for _, key := range keys {
			fmt.Fprintf(&out, "\t\t%q: {\n", key)
			for _, name := range entry.data.domains[key] {
				fmt.Fprintf(&out, "\t\t\t%q,\n", name)
			}
			fmt.Fprintln(&out, "\t\t},")
		}
		fmt.Fprintln(&out, "\t},")
	}
	fmt.Fprintln(&out, "}")
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(*output, formatted, 0644)
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
