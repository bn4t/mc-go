// Command genstructures packs every structure template the server jar
// ships (data/minecraft/structure/**/*.nbt) into one gzipped, base64
// blob, so worldgen features that place templates (fossils, template
// features, later jigsaw structures) can read them without the jar.
//
// Source class: jar resources — the unpacked 26.2 server jar
// (vanilla/versions/26.2/server-26.2.jar, created by running the
// bundler once, see README.md). Each template's NBT is gunzipped and
// stored byte for byte; nothing is parsed or rewritten. The header
// records the SHA-256 of the packed plain bytes.
//
// Packed layout (plain, before gzip): entries sorted by name, each a
// 4-byte big-endian name length, the name ("fossil/skull_1": the path
// under data/minecraft/structure/ without ".nbt"), a 4-byte big-endian
// data length and the uncompressed NBT bytes.
//
// Usage: go run ./tools/genstructures [vanilla/versions/26.2/server-26.2.jar]
// Writes internal/worldgen/structures_gen.go.
package main

import (
	"archive/zip"
	"bytes"
	"compress/gzip"
	"crypto/sha256"
	"encoding/base64"
	"encoding/binary"
	"fmt"
	"io"
	"log"
	"os"
	"sort"
	"strings"
)

const prefix = "data/minecraft/structure/"

func main() {
	jar := "vanilla/versions/26.2/server-26.2.jar"
	if len(os.Args) > 1 {
		jar = os.Args[1]
	}
	zr, err := zip.OpenReader(jar)
	if err != nil {
		log.Fatal(err)
	}
	defer zr.Close()
	entries := map[string][]byte{}
	for _, f := range zr.File {
		if !strings.HasPrefix(f.Name, prefix) || !strings.HasSuffix(f.Name, ".nbt") {
			continue
		}
		rc, err := f.Open()
		if err != nil {
			log.Fatal(err)
		}
		raw, err := io.ReadAll(rc)
		rc.Close()
		if err != nil {
			log.Fatal(err)
		}
		// Templates are gzipped NBT; keep the uncompressed bytes so the
		// outer gzip sees the redundancy across files.
		if len(raw) >= 2 && raw[0] == 0x1f && raw[1] == 0x8b {
			gr, err := gzip.NewReader(bytes.NewReader(raw))
			if err != nil {
				log.Fatalf("%s: %v", f.Name, err)
			}
			raw, err = io.ReadAll(gr)
			if err != nil {
				log.Fatalf("%s: %v", f.Name, err)
			}
		}
		entries[strings.TrimSuffix(strings.TrimPrefix(f.Name, prefix), ".nbt")] = raw
	}
	if len(entries) == 0 {
		log.Fatalf("no structure templates in %s", jar)
	}
	keys := make([]string, 0, len(entries))
	for k := range entries {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var plain bytes.Buffer
	var n [4]byte
	for _, k := range keys {
		binary.BigEndian.PutUint32(n[:], uint32(len(k)))
		plain.Write(n[:])
		plain.WriteString(k)
		binary.BigEndian.PutUint32(n[:], uint32(len(entries[k])))
		plain.Write(n[:])
		plain.Write(entries[k])
	}
	sum := sha256.Sum256(plain.Bytes())

	var gz bytes.Buffer
	zw, _ := gzip.NewWriterLevel(&gz, gzip.BestCompression)
	zw.Write(plain.Bytes())
	zw.Close()
	b64 := base64.StdEncoding.EncodeToString(gz.Bytes())

	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by tools/genstructures; DO NOT EDIT.\n")
	fmt.Fprintf(&out, "// Source: 26.2 server jar, data/minecraft/structure/**/*.nbt (gunzipped NBT).\n")
	fmt.Fprintf(&out, "// Entries: %d; packed plain SHA-256: %x\n\n", len(keys), sum)
	fmt.Fprintf(&out, "package worldgen\n\n")
	fmt.Fprintf(&out, "const structuresBlob = \"")
	for i := 0; i < len(b64); i += 4096 {
		end := min(i+4096, len(b64))
		if i > 0 {
			out.WriteString("\" +\n\t\"")
		}
		out.WriteString(b64[i:end])
	}
	out.WriteString("\"\n")
	if err := os.WriteFile("internal/worldgen/structures_gen.go", out.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("wrote %d templates, %d bytes plain, %d bytes gz, sha256 %x\n", len(keys), plain.Len(), gz.Len(), sum)
}
