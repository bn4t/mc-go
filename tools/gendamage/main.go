// Command gendamage turns the measured item damage values into the
// table mc-go ships.
//
// The measurement is in internal/server/testdata/vanilla-26.2/max_damage.tsv,
// one "name<TAB>max" line per item (-1 when the item takes no damage),
// written by TestCaptureVanillaMaxDamage: the real server wore each
// item to nothing with set_damage 0.0 and the damage read back names
// the max. Nothing here measures anything, and nothing here reads the
// jar: this is the recording turned into Go.
//
// Usage (from the repo root):
//
//	go run ./tools/gendamage
package main

import (
	"bufio"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strconv"
	"strings"
)

const (
	tsvPath = "internal/server/testdata/vanilla-26.2/max_damage.tsv"
	outPath = "internal/server/maxdamage_gen.go"
)

func main() {
	maxes := readTSV(tsvPath)

	var b strings.Builder
	fmt.Fprint(&b, `// Code generated by tools/gendamage from
// internal/server/testdata/vanilla-26.2/max_damage.tsv; DO NOT EDIT.

package server

import (
	"strings"

	"mc-go/internal/world"
)

// Item damage limits (durabilities), measured on the real server item
// by item rather than assumed: every item was worn to nothing with
// set_damage 0.0, and the damage read back names the max (see
// TestCaptureVanillaMaxDamage).
//
// Only damageable items are listed below:
`)
	damageable := 0
	for _, max := range maxes {
		if max > 0 {
			damageable++
		}
	}
	fmt.Fprintf(&b, "// %d of the %d items take damage, the rest take none.\n\n", damageable, len(maxes))

	var names []string
	for name, max := range maxes {
		if max > 0 {
			names = append(names, name)
		}
	}
	sort.Strings(names)
	b.WriteString("// damageableItems maps every damageable item to its maximum\n// damage: the damage value that wears one to nothing.\nvar damageableItems = map[string]int32{\n")
	for _, name := range names {
		fmt.Fprintf(&b, "\t%q: %d,\n", name, maxes[name])
	}
	b.WriteString("}\n\n")

	fmt.Fprint(&b, `// maxDamageOfItem is the damage value that wears the named item
// to nothing, or 0 when the item takes no damage. The name is a
// registry name without its minecraft: prefix, which is how the
// measured table spells them.
//
// An item the table does not hold reads as 0. That is every item the
// measurement refused to wear, and a name mc-go does not know about
// cannot reach a slot through any command it accepts.
func maxDamageOfItem(name string) int32 {
	return damageableItems[strings.TrimPrefix(name, "minecraft:")]
}

// MaxDamageOfID is the damage value that wears the item id to
// nothing, or 0 when it takes no damage.
func MaxDamageOfID(id int32) int32 {
	if name, ok := world.ItemName(id); ok {
		return maxDamageOfItem(name)
	}
	return 0
}
`)

	body, err := format.Source([]byte(b.String()))
	if err != nil {
		fatalf("generated source does not parse: %v", err)
	}
	if err := os.WriteFile(outPath, body, 0o644); err != nil {
		fatalf("write %s: %v", outPath, err)
	}
	fmt.Printf("generated %s: %d items, %d damageable\n", outPath, len(maxes), damageable)
}

// readTSV reads the measured table, refusing a file that is not a
// complete measurement: a duplicate name or an empty one would make the
// table silently smaller than the registry it describes.
func readTSV(path string) map[string]int32 {
	f, err := os.Open(path)
	if err != nil {
		fatalf("read %s: %v (run the capture first; see its comment)", path, err)
	}
	defer f.Close()
	maxes := map[string]int32{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" {
			continue
		}
		name, maxText, ok := strings.Cut(line, "\t")
		if !ok {
			fatalf("%s: line %q is not name<TAB>max", path, line)
		}
		max, err := strconv.Atoi(maxText)
		if err != nil {
			fatalf("%s: line %q has a bad max: %v", path, line, err)
		}
		if name == "" {
			fatalf("%s: line %q has an empty name", path, line)
		}
		if _, dup := maxes[name]; dup {
			fatalf("%s: duplicate name %q", path, name)
		}
		maxes[name] = int32(max)
	}
	if err := sc.Err(); err != nil {
		fatalf("read %s: %v", path, err)
	}
	return maxes
}

func fatalf(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "gendamage: "+format+"\n", args...)
	os.Exit(1)
}
