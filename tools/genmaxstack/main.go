// Command genmaxstack turns the measured item stack sizes into the table
// mc-go ships.
//
// The measurement is in internal/server/testdata/vanilla-26.2/max_stack.tsv,
// one "name<TAB>size" line per item, written by
// TestCaptureVanillaMaxStack: the real server was asked to put 64 of each
// item in a slot and its answer read back. Nothing here measures
// anything, and nothing here reads the jar: this is the recording turned
// into Go.
//
// Usage (from the repo root):
//
//	go run ./tools/genmaxstack
package main

import (
	"bufio"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strconv"
	"strings"
)

const (
	tsvPath = "internal/server/testdata/vanilla-26.2/max_stack.tsv"
	outPath = "internal/server/maxstack_gen.go"
)

func main() {
	sizes := readTSV(tsvPath)

	// The measured distribution is part of the file: a table that named
	// every item at 64 would be smaller than this one and wrong, and the
	// counts are how a reader sees that the exceptions are exceptions.
	bySize := map[int]int{}
	for _, size := range sizes {
		bySize[size]++
	}
	for size := range bySize {
		if size != 1 && size != 16 && size != 64 {
			fatalf("%s holds a stack size of %d, which is not one of the three the real server has", tsvPath, size)
		}
	}

	var b strings.Builder
	fmt.Fprint(&b, `// Code generated by tools/genmaxstack from
// internal/server/testdata/vanilla-26.2/max_stack.tsv; DO NOT EDIT.

package server

// Item stack sizes, measured on the real server item by item rather than
// assumed: every item was handed to it as a stack of 64, and its refusal
// names the size it does take (see TestCaptureVanillaMaxStack).
//
// The real server has exactly three stack sizes, and the two lists below
// are the ones that are not the common 64:
`)
	fmt.Fprintf(&b, "// %d of the %d items measure 1, %d measure 16, and the rest measure 64.\n\n",
		bySize[1], len(sizes), bySize[16])

	writeSet(&b, "unstackableItems", sizes, 1)
	writeSet(&b, "sixteenStackItems", sizes, 16)

	fmt.Fprint(&b, `// maxStackOfItem is how large a stack of the named item may be. The
// name is a registry name with its minecraft: prefix, which is how the
// measured table spells them.
//
// An item the table does not hold reads as 64. That is every item the
// measurement accepted, and a name mc-go does not know about cannot
// reach a slot through any command it accepts.
func maxStackOfItem(name string) int32 {
	switch {
	case unstackableItems[name]:
		return 1
	case sixteenStackItems[name]:
		return 16
	}
	return maxStack
}
`)

	body, err := format.Source([]byte(b.String()))
	if err != nil {
		fatalf("generated source does not parse: %v", err)
	}
	if err := os.WriteFile(outPath, body, 0o644); err != nil {
		fatalf("write %s: %v", outPath, err)
	}
	fmt.Printf("generated %s: %d items, %d at 1, %d at 16, %d at 64\n",
		outPath, len(sizes), bySize[1], bySize[16], bySize[64])
}

// writeSet emits one sorted name set for the items that stack to size.
func writeSet(b *strings.Builder, varName string, sizes map[string]int, size int) {
	var names []string
	for name, s := range sizes {
		if s == size {
			names = append(names, name)
		}
	}
	sort.Strings(names)
	fmt.Fprintf(b, "// %s is every item that stacks to %d.\nvar %s = map[string]bool{\n", varName, size, varName)
	for _, name := range names {
		fmt.Fprintf(b, "\t%q: true,\n", name)
	}
	b.WriteString("}\n\n")
}

// readTSV reads the measured table, refusing a file that is not a
// complete measurement: a duplicate name or an empty one would make the
// table silently smaller than the registry it describes.
func readTSV(path string) map[string]int {
	f, err := os.Open(path)
	if err != nil {
		fatalf("read %s: %v (run the capture first; see its comment)", path, err)
	}
	defer f.Close()
	sizes := map[string]int{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" {
			continue
		}
		name, sizeText, ok := strings.Cut(line, "\t")
		if !ok {
			fatalf("%s: line %q is not name<TAB>size", path, line)
		}
		size, err := strconv.Atoi(sizeText)
		if err != nil {
			fatalf("%s: %q: %v", path, line, err)
		}
		if name == "" {
			fatalf("%s: a line with no item name", path)
		}
		if _, dup := sizes[name]; dup {
			fatalf("%s: %s is measured twice", path, name)
		}
		sizes[name] = size
	}
	if err := sc.Err(); err != nil {
		fatalf("read %s: %v", path, err)
	}
	if len(sizes) == 0 {
		fatalf("%s holds no measurements", path)
	}
	return sizes
}

func fatalf(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "genmaxstack: "+format+"\n", args...)
	os.Exit(1)
}
