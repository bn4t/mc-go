// Command genworldgen packs the vanilla worldgen data the terrain
// generator consumes — noise parameters, density functions, noise
// settings, biomes, carvers, features, structures — plus the
// biome_parameters report into one gzipped, base64 JSON object keyed
// by path (e.g. "density_function/overworld/offset",
// "biome_parameters/overworld"), so the generated source stays small
// and the runtime decodes it once on first use.
//
// Source class: report/datapack — the 26.2 server's datagen output
// (`java -DbundlerMainClass=net.minecraft.data.Main -jar server-26.2.jar
// --all`, see README.md). Entries are copied verbatim (whitespace
// compacted only), so number spellings — which decide float32 versus
// float64 rounding — survive exactly. The header records the SHA-256 of
// the packed plain JSON.
//
// Usage: go run ./tools/genworldgen [vanilla/generated]
// Writes internal/worldgen/data_gen.go.
package main

import (
	"bytes"
	"compress/gzip"
	"crypto/sha256"
	"encoding/base64"
	"encoding/json"
	"fmt"
	"io/fs"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

var worldgenDirs = []string{
	"noise", "density_function", "noise_settings", "biome", "configured_carver",
	"configured_feature", "placed_feature", "structure", "structure_set",
	"template_pool", "processor_list", "multi_noise_biome_source_parameter_list",
	"world_preset", "flat_level_generator_preset",
}

func main() {
	root := "vanilla/generated"
	if len(os.Args) > 1 {
		root = os.Args[1]
	}
	entries := map[string]json.RawMessage{}
	add := func(base, prefix string) {
		err := filepath.WalkDir(base, func(p string, d fs.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if d.IsDir() || !strings.HasSuffix(p, ".json") {
				return nil
			}
			rel, _ := filepath.Rel(base, p)
			key := prefix + strings.TrimSuffix(filepath.ToSlash(rel), ".json")
			raw, err := os.ReadFile(p)
			if err != nil {
				return err
			}
			var buf bytes.Buffer
			if err := json.Compact(&buf, raw); err != nil {
				return fmt.Errorf("%s: %w", p, err)
			}
			entries[key] = buf.Bytes()
			return nil
		})
		if err != nil {
			log.Fatal(err)
		}
	}
	for _, d := range worldgenDirs {
		add(filepath.Join(root, "data/minecraft/worldgen", d), d+"/")
	}
	add(filepath.Join(root, "reports/biome_parameters/minecraft"), "biome_parameters/")
	for _, t := range []string{"fluid", "worldgen/biome", "worldgen/structure", "worldgen/configured_feature", "worldgen/flat_level_generator_preset", "worldgen/world_preset"} {
		add(filepath.Join(root, "data/minecraft/tags", t), "tags/"+t+"/")
	}
	if len(entries) == 0 {
		log.Fatalf("no worldgen data under %s", root)
	}

	keys := make([]string, 0, len(entries))
	for k := range entries {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var plain bytes.Buffer
	plain.WriteString("{")
	for i, k := range keys {
		if i > 0 {
			plain.WriteString(",")
		}
		kb, _ := json.Marshal(k)
		plain.Write(kb)
		plain.WriteString(":")
		plain.Write(entries[k])
	}
	plain.WriteString("}")
	sum := sha256.Sum256(plain.Bytes())

	var gz bytes.Buffer
	zw, _ := gzip.NewWriterLevel(&gz, gzip.BestCompression)
	zw.Write(plain.Bytes())
	zw.Close()
	b64 := base64.StdEncoding.EncodeToString(gz.Bytes())

	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by tools/genworldgen; DO NOT EDIT.\n")
	fmt.Fprintf(&out, "// Source: 26.2 datagen output (worldgen registries + biome_parameters report).\n")
	fmt.Fprintf(&out, "// Entries: %d; plain JSON SHA-256: %x\n\n", len(keys), sum)
	fmt.Fprintf(&out, "package worldgen\n\n")
	fmt.Fprintf(&out, "const worldgenBlob = \"")
	for i := 0; i < len(b64); i += 4096 {
		end := min(i+4096, len(b64))
		if i > 0 {
			out.WriteString("\" +\n\t\"")
		}
		out.WriteString(b64[i:end])
	}
	out.WriteString("\"\n")
	if err := os.WriteFile("internal/worldgen/data_gen.go", out.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("wrote %d entries, %d bytes gz, sha256 %x\n", len(keys), gz.Len(), sum)
}
