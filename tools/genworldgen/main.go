// Command genworldgen turns the vanilla 26.2 worldgen datapack (the
// data report the official server writes with --reports/--server) into
// Go tables in internal/worldgen. The inputs are data definitions —
// noise parameters, density-function graphs, noise settings — not code.
//
// Usage: go run ./tools/genworldgen [-root .]
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

func main() {
	root := flag.String("root", ".", "repository root")
	flag.Parse()
	data := filepath.Join(*root, "vanilla", "generated", "data", "minecraft", "worldgen")
	h := sha256.New()
	noises := readTree(filepath.Join(data, "noise"), h)
	functions := readTree(filepath.Join(data, "density_function"), h)
	settings := readTree(filepath.Join(data, "noise_settings"), h)

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tools/genworldgen; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// Source: the official 26.2 server's generated worldgen data\n")
	fmt.Fprintf(&b, "// (vanilla/generated/data/minecraft/worldgen), inputs SHA-256 %x.\n\n", h.Sum(nil))
	fmt.Fprintf(&b, "package worldgen\n\n")
	fmt.Fprintf(&b, "// noiseParams are the registered noise definitions by identifier.\n")
	fmt.Fprintf(&b, "var noiseParams = map[string]NoiseParams{\n")
	for _, k := range sortedKeys(noises) {
		var p struct {
			FirstOctave int       `json:"firstOctave"`
			Amplitudes  []float64 `json:"amplitudes"`
		}
		must(json.Unmarshal(noises[k], &p))
		amps := make([]string, len(p.Amplitudes))
		for i, a := range p.Amplitudes {
			amps[i] = strconv.FormatFloat(a, 'g', -1, 64)
		}
		fmt.Fprintf(&b, "\t%q: {%d, []float64{%s}},\n", "minecraft:"+k, p.FirstOctave, strings.Join(amps, ", "))
	}
	fmt.Fprintf(&b, "}\n\n")

	fmt.Fprintf(&b, "// densityFunctions are the registered density functions by identifier.\n")
	fmt.Fprintf(&b, "var densityFunctions = map[string]*Spec{\n")
	for _, k := range sortedKeys(functions) {
		fmt.Fprintf(&b, "\t%q: %s,\n", "minecraft:"+k, densitySpec(decode(functions[k])))
	}
	fmt.Fprintf(&b, "}\n\n")

	fmt.Fprintf(&b, "// noiseSettings are the registered noise generator settings by identifier.\n")
	fmt.Fprintf(&b, "var noiseSettings = map[string]*NoiseSettings{\n")
	for _, k := range sortedKeys(settings) {
		fmt.Fprintf(&b, "\t%q: %s,\n", "minecraft:"+k, settingsLiteral(decode(settings[k]).(map[string]any)))
	}
	fmt.Fprintf(&b, "}\n")
	write(filepath.Join(*root, "internal/worldgen/worldgen_gen.go"), b.Bytes())
}

func decode(raw json.RawMessage) any {
	d := json.NewDecoder(bytes.NewReader(raw))
	d.UseNumber()
	var v any
	must(d.Decode(&v))
	return v
}

// routerFields are the noise router's slots in NoiseRouter field order.
var routerFields = []struct{ json, field string }{
	{"barrier", "Barrier"}, {"fluid_level_floodedness", "FluidLevelFloodedness"},
	{"fluid_level_spread", "FluidLevelSpread"}, {"lava", "Lava"},
	{"temperature", "Temperature"}, {"vegetation", "Vegetation"},
	{"continents", "Continents"}, {"erosion", "Erosion"}, {"depth", "Depth"},
	{"ridges", "Ridges"}, {"preliminary_surface_level", "PreliminarySurfaceLevel"},
	{"final_density", "FinalDensity"}, {"vein_toggle", "VeinToggle"},
	{"vein_ridged", "VeinRidged"}, {"vein_gap", "VeinGap"},
}

func settingsLiteral(m map[string]any) string {
	noise := m["noise"].(map[string]any)
	var r strings.Builder
	for _, f := range routerFields {
		fmt.Fprintf(&r, "%s: %s,\n", f.field, densitySpec(m["noise_router"].(map[string]any)[f.json]))
	}
	return fmt.Sprintf("{MinY: %s, Height: %s, SizeHorizontal: %s, SizeVertical: %s, SeaLevel: %s, "+
		"DefaultBlock: %s, DefaultFluid: %s, AquifersEnabled: %v, OreVeinsEnabled: %v, LegacyRandomSource: %v, "+
		"DisableMobGeneration: %v, Router: Router{\n%s}}",
		noise["min_y"], noise["height"], noise["size_horizontal"], noise["size_vertical"], m["sea_level"],
		blockState(m["default_block"]), blockState(m["default_fluid"]), m["aquifers_enabled"], m["ore_veins_enabled"],
		m["legacy_random_source"], m["disable_mob_generation"], r.String())
}

func blockState(v any) string {
	m := v.(map[string]any)
	props, _ := m["Properties"].(map[string]any)
	if len(props) == 0 {
		return fmt.Sprintf("BlockState{Name: %q}", m["Name"])
	}
	var kv []string
	for _, k := range sortedKeys(props) {
		kv = append(kv, fmt.Sprintf("%q: %q", k, props[k]))
	}
	return fmt.Sprintf("BlockState{Name: %q, Props: map[string]string{%s}}", m["Name"], strings.Join(kv, ", "))
}

func num(v any) string {
	n, ok := v.(json.Number)
	if !ok {
		fatal("expected a number, got %T %v", v, v)
	}
	f, err := n.Float64()
	must(err)
	return strconv.FormatFloat(f, 'g', -1, 64)
}

func num32(v any) string {
	n := v.(json.Number)
	f, err := strconv.ParseFloat(string(n), 32)
	must(err)
	return strconv.FormatFloat(f, 'g', -1, 32)
}

var unaryKinds = map[string]string{
	"abs": "KAbs", "square": "KSquare", "cube": "KCube", "half_negative": "KHalfNegative",
	"quarter_negative": "KQuarterNegative", "invert": "KInvert", "squeeze": "KSqueeze",
	"interpolated": "KInterpolated", "flat_cache": "KFlatCache", "cache_2d": "KCache2D",
	"cache_once": "KCacheOnce", "cache_all_in_cell": "KCacheAllInCell", "blend_density": "KBlendDensity",
}

var binaryKinds = map[string]string{"add": "KAdd", "mul": "KMul", "min": "KMin", "max": "KMax"}

var leafKinds = map[string]string{
	"blend_alpha": "KBlendAlpha", "blend_offset": "KBlendOffset", "beardifier": "KBeardifier",
	"end_islands": "KEndIslands",
}

// densitySpec renders a density function definition — a constant, a
// reference or an inline object — as a constructor expression.
func densitySpec(v any) string {
	switch v := v.(type) {
	case json.Number:
		return "dfConst(" + num(v) + ")"
	case string:
		return fmt.Sprintf("dfRef(%q)", qualify(v))
	case map[string]any:
		t := strings.TrimPrefix(v["type"].(string), "minecraft:")
		if k, ok := unaryKinds[t]; ok {
			return fmt.Sprintf("dfOp(%s, %s)", k, densitySpec(v["argument"]))
		}
		if k, ok := binaryKinds[t]; ok {
			return fmt.Sprintf("dfOp(%s, %s, %s)", k, densitySpec(v["argument1"]), densitySpec(v["argument2"]))
		}
		if k, ok := leafKinds[t]; ok {
			return fmt.Sprintf("dfLeaf(%s)", k)
		}
		switch t {
		case "constant":
			return "dfConst(" + num(v["argument"]) + ")"
		case "clamp":
			return fmt.Sprintf("dfClamp(%s, %s, %s)", densitySpec(v["input"]), num(v["min"]), num(v["max"]))
		case "range_choice":
			return fmt.Sprintf("dfRange(%s, %s, %s, %s, %s)", densitySpec(v["input"]), num(v["min_inclusive"]),
				num(v["max_exclusive"]), densitySpec(v["when_in_range"]), densitySpec(v["when_out_of_range"]))
		case "y_clamped_gradient":
			return fmt.Sprintf("dfNum(KYGradient, %s, %s, %s, %s)", num(v["from_y"]), num(v["to_y"]),
				num(v["from_value"]), num(v["to_value"]))
		case "noise":
			return fmt.Sprintf("dfNoise(%q, %s, %s)", qualify(v["noise"].(string)), num(v["xz_scale"]), num(v["y_scale"]))
		case "shifted_noise":
			return fmt.Sprintf("dfShifted(%q, %s, %s, %s, %s, %s)", qualify(v["noise"].(string)),
				densitySpec(v["shift_x"]), densitySpec(v["shift_y"]), densitySpec(v["shift_z"]),
				num(v["xz_scale"]), num(v["y_scale"]))
		case "shift_a", "shift_b", "shift":
			k := map[string]string{"shift_a": "KShiftA", "shift_b": "KShiftB", "shift": "KShift"}[t]
			return fmt.Sprintf("dfShiftNoise(%s, %q)", k, qualify(v["argument"].(string)))
		case "interval_select":
			var th []string
			for _, x := range v["thresholds"].([]any) {
				th = append(th, num(x))
			}
			var fns []string
			for _, f := range v["functions"].([]any) {
				fns = append(fns, densitySpec(f))
			}
			return fmt.Sprintf("dfInterval(%s, []float64{%s}, %s)", densitySpec(v["input"]),
				strings.Join(th, ", "), strings.Join(fns, ", "))
		case "find_top_surface":
			return fmt.Sprintf("dfTopSurface(%s, %s, %s, %s)", densitySpec(v["density"]),
				densitySpec(v["upper_bound"]), num(v["lower_bound"]), num(v["cell_height"]))
		case "spline":
			return "dfSpline(" + splineSpec(v["spline"]) + ")"
		case "old_blended_noise":
			return fmt.Sprintf("dfNum(KOldBlendedNoise, %s, %s, %s, %s, %s)", num(v["xz_scale"]), num(v["y_scale"]),
				num(v["xz_factor"]), num(v["y_factor"]), num(v["smear_scale_multiplier"]))
		}
		fatal("unsupported density function type %q", t)
	}
	fatal("unsupported density function value %T", v)
	return ""
}

func splineSpec(v any) string {
	if n, ok := v.(json.Number); ok {
		return "splConst(" + num32(n) + ")"
	}
	m := v.(map[string]any)
	var pts []string
	for _, p := range m["points"].([]any) {
		p := p.(map[string]any)
		pts = append(pts, fmt.Sprintf("knot(%s, %s, %s)", num32(p["location"]), splineSpec(p["value"]), num32(p["derivative"])))
	}
	return fmt.Sprintf("spl(%s, %s)", densitySpec(m["coordinate"]), strings.Join(pts, ", "))
}

func qualify(id string) string {
	if strings.Contains(id, ":") {
		return id
	}
	return "minecraft:" + id
}

// readTree loads every JSON file under dir keyed by its slash path
// without the extension, folding each file's bytes into h in key order.
func readTree(dir string, h interface{ Write([]byte) (int, error) }) map[string]json.RawMessage {
	out := map[string]json.RawMessage{}
	must(filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(path, ".json") {
			return err
		}
		rel, err := filepath.Rel(dir, path)
		if err != nil {
			return err
		}
		raw, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		out[strings.TrimSuffix(filepath.ToSlash(rel), ".json")] = raw
		return nil
	}))
	for _, k := range sortedKeys(out) {
		h.Write([]byte(k))
		h.Write(out[k])
	}
	return out
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func write(path string, src []byte) {
	out, err := format.Source(src)
	if err != nil {
		fatal("format %s: %v\n%s", path, err, src)
	}
	must(os.WriteFile(path, out, 0644))
}

func must(err error) {
	if err != nil {
		fatal("%v", err)
	}
}

func fatal(message string, args ...any) { fmt.Fprintf(os.Stderr, message+"\n", args...); os.Exit(1) }
