// Command worldgenprobe records reference values from the official 26.2
// server's world-generation classes at runtime into
// internal/worldgen/testdata, the goldens the Go implementation is
// tested against: random draws, positional sources, noise samples and
// noise-router outputs (WorldgenProbe.java, vanilla_probe.tsv), and
// noise-stage chunk fills (ChunkFillProbe.java, chunk_fill.tsv.gz). The
// probes call the running game's own code; nothing is decompiled.
// Regeneration needs JDK 25 and the unpacked server (vanilla/versions,
// vanilla/libraries).
//
// Usage: go run ./tools/worldgenprobe [-jdk dir] [-root .]
package main

import (
	"bytes"
	"compress/gzip"
	"crypto/sha256"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	jdk := flag.String("jdk", "", "directory containing java and javac, otherwise PATH")
	root := flag.String("root", ".", "repository root")
	flag.Parse()
	base := filepath.Join(*root, "vanilla")
	jar := filepath.Join(base, "versions", "26.2", "server-26.2.jar")
	classpath := []string{jar}
	must(filepath.WalkDir(filepath.Join(base, "libraries"), func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() && strings.HasSuffix(path, ".jar") {
			classpath = append(classpath, path)
		}
		return nil
	}))
	sort.Strings(classpath[1:])
	cp := strings.Join(classpath, string(os.PathListSeparator))
	temp, err := os.MkdirTemp("", "mcgo-worldgen-probe-")
	must(err)
	defer os.RemoveAll(temp)
	run(filepath.Join(*jdk, "javac"), "-cp", cp, "-d", temp,
		filepath.Join(*root, "tools/worldgenprobe/WorldgenProbe.java"),
		filepath.Join(*root, "tools/worldgenprobe/ChunkFillProbe.java"))
	jarSum := sha256.Sum256(must1(os.ReadFile(jar)))
	testdata := filepath.Join(*root, "internal/worldgen/testdata")
	must(os.MkdirAll(testdata, 0o755))
	for _, probe := range []struct{ class, file string }{
		{"WorldgenProbe", "vanilla_probe.tsv"},
		{"ChunkFillProbe", "chunk_fill.tsv.gz"},
	} {
		out := filepath.Join(temp, probe.class+".tsv")
		run(filepath.Join(*jdk, "java"), "-cp", temp+string(os.PathListSeparator)+cp, probe.class, out)
		raw, err := os.ReadFile(out)
		must(err)
		var b bytes.Buffer
		fmt.Fprintf(&b, "# Generated by tools/worldgenprobe (%s); DO NOT EDIT.\n", probe.class)
		fmt.Fprintf(&b, "# Source: runtime calls into the official 26.2 server jar (SHA-256 %x).\n", jarSum)
		b.Write(raw)
		data := b.Bytes()
		if strings.HasSuffix(probe.file, ".gz") {
			var z bytes.Buffer
			w, err := gzip.NewWriterLevel(&z, gzip.BestCompression)
			must(err)
			_, err = w.Write(data)
			must(err)
			must(w.Close())
			data = z.Bytes()
		}
		must(os.WriteFile(filepath.Join(testdata, probe.file), data, 0o644))
	}
}

func run(command string, args ...string) {
	out, err := exec.Command(command, args...).CombinedOutput()
	if err != nil {
		fatal("%s: %v\n%s", command, err, out)
	}
}

func must1[T any](v T, err error) T {
	must(err)
	return v
}

func must(err error) {
	if err != nil {
		fatal("%v", err)
	}
}

func fatal(message string, args ...any) { fmt.Fprintf(os.Stderr, message+"\n", args...); os.Exit(1) }
