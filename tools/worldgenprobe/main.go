// Command worldgenprobe records reference values from the official 26.2
// server's world-generation classes at runtime — random draws,
// positional sources, noise samples and noise-router outputs — into
// internal/worldgen/testdata/vanilla_probe.tsv, the goldens the Go
// implementation is tested against. WorldgenProbe.java only calls
// public entry points of the running game; nothing is decompiled.
// Regeneration needs JDK 25 and the unpacked server (vanilla/versions,
// vanilla/libraries).
//
// Usage: go run ./tools/worldgenprobe [-jdk dir] [-root .]
package main

import (
	"bytes"
	"crypto/sha256"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	jdk := flag.String("jdk", "", "directory containing java and javac, otherwise PATH")
	root := flag.String("root", ".", "repository root")
	flag.Parse()
	base := filepath.Join(*root, "vanilla")
	jar := filepath.Join(base, "versions", "26.2", "server-26.2.jar")
	classpath := []string{jar}
	must(filepath.WalkDir(filepath.Join(base, "libraries"), func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() && strings.HasSuffix(path, ".jar") {
			classpath = append(classpath, path)
		}
		return nil
	}))
	sort.Strings(classpath[1:])
	cp := strings.Join(classpath, string(os.PathListSeparator))
	temp, err := os.MkdirTemp("", "mcgo-worldgen-probe-")
	must(err)
	defer os.RemoveAll(temp)
	run(filepath.Join(*jdk, "javac"), "-cp", cp, "-d", temp, filepath.Join(*root, "tools/worldgenprobe/WorldgenProbe.java"))
	out := filepath.Join(temp, "probe.tsv")
	run(filepath.Join(*jdk, "java"), "-cp", temp+string(os.PathListSeparator)+cp, "WorldgenProbe", out)
	raw, err := os.ReadFile(out)
	must(err)
	jarSum := sha256.Sum256(must1(os.ReadFile(jar)))
	var b bytes.Buffer
	fmt.Fprintf(&b, "# Generated by tools/worldgenprobe; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "# Source: runtime calls into the official 26.2 server jar (SHA-256 %x).\n", jarSum)
	b.Write(raw)
	dst := filepath.Join(*root, "internal/worldgen/testdata/vanilla_probe.tsv")
	must(os.MkdirAll(filepath.Dir(dst), 0o755))
	must(os.WriteFile(dst, b.Bytes(), 0o644))
}

func run(command string, args ...string) {
	out, err := exec.Command(command, args...).CombinedOutput()
	if err != nil {
		fatal("%s: %v\n%s", command, err, out)
	}
}

func must1[T any](v T, err error) T {
	must(err)
	return v
}

func must(err error) {
	if err != nil {
		fatal("%v", err)
	}
}

func fatal(message string, args ...any) { fmt.Fprintf(os.Stderr, message+"\n", args...); os.Exit(1) }
