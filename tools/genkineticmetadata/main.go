// Command genkineticmetadata generates factual default kinetic-weapon metadata.
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"math"
	"os"
	"sort"
	"strconv"
	"strings"
)

const input = "internal/server/testdata/vanilla-26.2/kinetic_weapon_metadata.tsv"
const output = "internal/server/kineticinfo_gen.go"

func main() {
	data, err := os.ReadFile(input)
	if err != nil {
		panic(err)
	}
	rows := map[string][]string{}
	scan := bufio.NewScanner(bytes.NewReader(data))
	for scan.Scan() {
		line := scan.Text()
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		f := strings.Split(line, "\t")
		if len(f) != 18 || !strings.HasPrefix(f[0], "minecraft:") || !strings.HasSuffix(f[0], "_spear") {
			panic("invalid kinetic row: " + line)
		}
		name := strings.TrimPrefix(f[0], "minecraft:")
		if _, ok := rows[name]; ok {
			panic("duplicate kinetic item: " + name)
		}
		for _, i := range []int{1, 2, 3, 6, 9, 14, 15} {
			value, e := strconv.Atoi(f[i])
			if e != nil || value < 0 {
				panic("invalid integer: " + line)
			}
		}
		for _, i := range []int{4, 5, 7, 8, 10, 11, 12, 13} {
			value, e := strconv.ParseFloat(f[i], 64)
			if e != nil || math.IsNaN(value) || math.IsInf(value, 0) || value < 0 || float64(float32(value)) != value {
				panic("invalid promoted float: " + line)
			}
		}
		if !strings.HasPrefix(f[16], "minecraft:") || !strings.HasPrefix(f[17], "minecraft:") {
			panic("invalid sound names: " + line)
		}
		rows[name] = f
	}
	if err := scan.Err(); err != nil {
		panic(err)
	}
	if len(rows) != 7 {
		panic(fmt.Sprintf("want7 kinetic items, got%d", len(rows)))
	}
	names := make([]string, 0, len(rows))
	for name := range rows {
		names = append(names, name)
	}
	sort.Strings(names)
	var out strings.Builder
	fmt.Fprint(&out, "// Code generated by tools/genkineticmetadata from Java 26.2 public component getters; DO NOT EDIT.\n\npackage server\n\ntype kineticConditionInfo struct {\n maxDurationTicks int\n minSpeed, minRelativeSpeed float64\n}\n\ntype kineticWeaponInfo struct {\n contactCooldownTicks, delayTicks int\n dismount, knockback, damage kineticConditionInfo\n forwardMovement, damageMultiplier float64\n useSound, hitSound int32\n}\n\nvar kineticWeaponMetadata = map[string]kineticWeaponInfo{\n")
	for _, name := range names {
		f := rows[name]
		fmt.Fprintf(&out, "%q: {%s,%s,kineticConditionInfo{%s,%s,%s},kineticConditionInfo{%s,%s,%s},kineticConditionInfo{%s,%s,%s},%s,%s,%s,%s},\n", name, f[1], f[2], f[3], f[4], f[5], f[6], f[7], f[8], f[9], f[10], f[11], f[12], f[13], f[14], f[15])
	}
	fmt.Fprint(&out, "}\n")
	formatted, err := format.Source([]byte(out.String()))
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(output, formatted, 0644); err != nil {
		panic(err)
	}
}
