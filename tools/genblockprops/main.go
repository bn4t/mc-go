// Command genblockprops measures, by runtime calls against the local
// official 26.2 server distribution, the block-state facts world
// generation consults (air, blocks motion, solid, replaceable, fluid,
// leaves, sturdy faces, full-block collision) and emits
// internal/worldgen/blockprops_gen.go: every block's property layout
// (so a canonical state string maps to its registry id) and one flag
// word per state. It does not decompile or translate methods: the probe
// only asks the running game for each state's facts. Regeneration needs
// JDK 25 and the unpacked server (vanilla/versions, vanilla/libraries).
//
// Usage: go run ./tools/genblockprops [-jdk dir] [-root .]
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"encoding/base64"
	"encoding/binary"
	"flag"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

type state struct {
	id    int
	block string
	props map[string]string
	flags uint64
}

type propLayout struct {
	name   string
	values []string
	stride int
}

func main() {
	jdk := flag.String("jdk", "", "directory containing java and javac, otherwise PATH")
	root := flag.String("root", ".", "repository root")
	flag.Parse()
	base := filepath.Join(*root, "vanilla")
	jar := filepath.Join(base, "versions", "26.2", "server-26.2.jar")
	classpath := []string{jar}
	must(filepath.WalkDir(filepath.Join(base, "libraries"), func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() && strings.HasSuffix(path, ".jar") {
			classpath = append(classpath, path)
		}
		return nil
	}))
	sort.Strings(classpath[1:])
	cp := strings.Join(classpath, string(os.PathListSeparator))
	temp, err := os.MkdirTemp("", "mcgo-block-props-")
	must(err)
	defer os.RemoveAll(temp)
	run(filepath.Join(*jdk, "javac"), "-cp", cp, "-d", temp, filepath.Join(*root, "tools/genblockprops/BlockPropsProbe.java"))
	out := filepath.Join(temp, "props.tsv")
	run(filepath.Join(*jdk, "java"), "-cp", temp+string(os.PathListSeparator)+cp, "BlockPropsProbe", out)
	raw, err := os.ReadFile(out)
	must(err)

	var blocks []string
	defaults := map[string]int{}
	classes := map[string][5]string{}
	var states []state
	sc := bufio.NewScanner(bytes.NewReader(raw))
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	for sc.Scan() {
		f := strings.Split(sc.Text(), "\t")
		switch f[0] {
		case "block":
			name := strings.TrimPrefix(f[1], "minecraft:")
			blocks = append(blocks, name)
			defaults[name] = atoi(f[2])
			classes[name] = [5]string{f[3], f[4], f[5], f[6], f[7]}
		case "state":
			id := atoi(f[1])
			if id != len(states) {
				fatal("state ids not dense at %d", id)
			}
			name, rest, _ := strings.Cut(strings.TrimPrefix(f[2], "minecraft:"), "[")
			props := map[string]string{}
			if rest != "" {
				for _, kv := range strings.Split(strings.TrimSuffix(rest, "]"), ",") {
					k, v, _ := strings.Cut(kv, "=")
					props[k] = v
				}
			}
			states = append(states, state{id: id, block: name, props: props, flags: parseUint(f[3])})
		}
	}

	// Lay out each block's properties: the values in first-seen order
	// and the stride that makes id = first + sum(value index * stride).
	type layout struct {
		first, count, def int
		props             []propLayout
	}
	layouts := map[string]*layout{}
	for _, s := range states {
		l := layouts[s.block]
		if l == nil {
			l = &layout{first: s.id, def: defaults[s.block]}
			layouts[s.block] = l
			names := make([]string, 0, len(s.props))
			for k := range s.props {
				names = append(names, k)
			}
			sort.Strings(names)
			for _, k := range names {
				l.props = append(l.props, propLayout{name: k})
			}
		}
		l.count++
		for i := range l.props {
			p := &l.props[i]
			v := s.props[p.name]
			if indexOf(p.values, v) < 0 {
				p.values = append(p.values, v)
				if len(p.values) == 2 {
					p.stride = s.id - l.first
				}
			}
		}
	}
	for _, s := range states {
		l := layouts[s.block]
		id := l.first
		for _, p := range l.props {
			id += indexOf(p.values, s.props[p.name]) * p.stride
		}
		if id != s.id {
			fatal("state %d (%s %v) does not follow the stride layout", s.id, s.block, s.props)
		}
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tools/genblockprops; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// Source: runtime calls into the official 26.2 server jar\n")
	fmt.Fprintf(&b, "// (SHA-256 %x), measurement SHA-256 %x.\n\n", sha256OfFile(jar), sha256.Sum256(raw))
	fmt.Fprintf(&b, "package worldgen\n\n")
	fmt.Fprintf(&b, "// blockLayouts are the blocks in registry order: each block's first\n")
	fmt.Fprintf(&b, "// state id, default state id, properties (name, values, stride), class,\n")
	fmt.Fprintf(&b, "// canSurvive and mayPlaceOn declaring classes, support tag and\n")
	fmt.Fprintf(&b, "// updateShape declaring class.\n")
	fmt.Fprintf(&b, "var blockLayouts = []blockLayout{\n")
	for _, name := range blocks {
		l := layouts[name]
		var ps []string
		for _, p := range l.props {
			ps = append(ps, fmt.Sprintf("{%q, []string{%s}, %d}", p.name, quoteAll(p.values), p.stride))
		}
		c := classes[name]
		fmt.Fprintf(&b, "\t{%q, %d, %d, %d, []propLayout{%s}, %q, %q, %q, %q, %q},\n", name, l.first, l.count, l.def,
			strings.Join(ps, ", "), c[0], c[1], c[2], c[3], c[4])
	}
	fmt.Fprintf(&b, "}\n\n")
	flags := make([]byte, 8*len(states))
	for _, s := range states {
		binary.LittleEndian.PutUint64(flags[8*s.id:], s.flags)
	}
	fmt.Fprintf(&b, "// stateFlagData holds one little-endian 64-bit flag word per state id\n")
	fmt.Fprintf(&b, "// (see the bsf constants), base64-encoded.\n")
	fmt.Fprintf(&b, "const stateFlagData = %q\n\n", base64.StdEncoding.EncodeToString(flags))
	fmt.Fprintf(&b, "// stateCount is the number of block states.\n")
	fmt.Fprintf(&b, "const stateCount = %d\n", len(states))
	src, err := format.Source(b.Bytes())
	must(err)
	must(os.WriteFile(filepath.Join(*root, "internal/worldgen/blockprops_gen.go"), src, 0o644))
}

func indexOf(list []string, v string) int {
	for i, s := range list {
		if s == v {
			return i
		}
	}
	return -1
}

func quoteAll(list []string) string {
	q := make([]string, len(list))
	for i, s := range list {
		q[i] = strconv.Quote(s)
	}
	return strings.Join(q, ", ")
}

func parseUint(s string) uint64 {
	n, err := strconv.ParseUint(s, 10, 64)
	must(err)
	return n
}

func atoi(s string) int {
	n, err := strconv.Atoi(s)
	must(err)
	return n
}

func sha256OfFile(path string) [32]byte {
	raw, err := os.ReadFile(path)
	must(err)
	return sha256.Sum256(raw)
}

func run(command string, args ...string) {
	out, err := exec.Command(command, args...).CombinedOutput()
	if err != nil {
		fatal("%s: %v\n%s", command, err, out)
	}
}

func must(err error) {
	if err != nil {
		fatal("%v", err)
	}
}

func fatal(message string, args ...any) { fmt.Fprintf(os.Stderr, message+"\n", args...); os.Exit(1) }
