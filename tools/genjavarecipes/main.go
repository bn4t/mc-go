// genjavarecipes derives factual recipe-name/display associations from the
// official sorted recipe datapack and pins the matching independently captured
// RecipeBookAdd packet. It imports no Minecraft implementation or library.
package main

import (
	"archive/zip"
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"io"
	"os"
	"sort"
	"strings"
)

func main() {
	jar := flag.String("jar", "vanilla/measure-26.1/versions/26.1/server-26.1.jar", "official unbundled775 jar")
	wire := flag.String("wire", "", "captured complete775 RecipeBookAdd body")
	output := flag.String("out", "internal/server/java775_recipes_gen.go", "generated factual names table")
	flag.Parse()
	if *wire == "" {
		panic("-wire is required")
	}
	jarBytes, err := os.ReadFile(*jar)
	must(err)
	wireBytes, err := os.ReadFile(*wire)
	must(err)
	z, err := zip.NewReader(bytes.NewReader(jarBytes), int64(len(jarBytes)))
	must(err)
	type recipe struct {
		Type          string          `json:"type"`
		MaterialCount json.RawMessage `json:"material_count"`
	}
	recipes := map[string]recipe{}
	for _, f := range z.File {
		if !strings.HasPrefix(f.Name, "data/minecraft/recipe/") || !strings.HasSuffix(f.Name, ".json") {
			continue
		}
		r, err := f.Open()
		must(err)
		raw, err := io.ReadAll(r)
		must(err)
		must(r.Close())
		var value recipe
		must(json.Unmarshal(raw, &value))
		name := strings.TrimSuffix(strings.TrimPrefix(f.Name, "data/minecraft/recipe/"), ".json")
		recipes[name] = value
	}
	var names []string
	for name := range recipes {
		names = append(names, name)
	}
	sort.Strings(names)
	var displays []string
	for _, name := range names {
		r := recipes[name]
		switch r.Type {
		case "minecraft:crafting_shaped", "minecraft:crafting_shapeless", "minecraft:crafting_dye", "minecraft:crafting_transmute", "minecraft:crafting_imbue", "minecraft:stonecutting", "minecraft:smelting", "minecraft:blasting", "minecraft:smoking", "minecraft:campfire_cooking", "minecraft:smithing_transform", "minecraft:smithing_trim":
		default:
			continue
		}
		count := 1
		if len(r.MaterialCount) > 0 {
			var interval struct {
				Max int `json:"max"`
			}
			if json.Unmarshal(r.MaterialCount, &interval) == nil && interval.Max > 0 {
				count = interval.Max
			} else {
				must(json.Unmarshal(r.MaterialCount, &count))
			}
		}
		if count < 1 || count > 64 {
			panic("invalid recipe display expansion")
		}
		for range count {
			displays = append(displays, name)
		}
	}
	if len(recipes) != 1515 || len(displays) != 1498 {
		panic(fmt.Sprintf("unexpected775 recipe facts: recipes%d displays%d", len(recipes), len(displays)))
	}
	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by tools/genjavarecipes; DO NOT EDIT.")
	fmt.Fprintln(&b, "// Source classes: official report/datapack facts and independent wire observation.")
	fmt.Fprintf(&b, "// Inner jar SHA256: %x\n// RecipeBookAdd SHA256: %x\n", sha256.Sum256(jarBytes), sha256.Sum256(wireBytes))
	fmt.Fprintf(&b, "package server\n\nconst java775RecipeCount = %d\n\nvar java775RecipeDisplayNames = [...]string{\n", len(recipes))
	for _, name := range displays {
		fmt.Fprintf(&b, "%q,\n", name)
	}
	fmt.Fprintln(&b, "}")
	generated, err := format.Source(b.Bytes())
	must(err)
	must(os.WriteFile(*output, generated, 0644))
	fmt.Printf("recipes=%d displays=%d wireSHA256=%s\n", len(recipes), len(displays), hex.EncodeToString(hash(wireBytes)))
}
func hash(b []byte) []byte { h := sha256.Sum256(b); return h[:] }
func must(err error) {
	if err != nil {
		panic(err)
	}
}
