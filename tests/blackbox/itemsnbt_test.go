// runItemSNBTScript joins a server, runs the script, and returns one
// normalized reply per command.
func runItemSNBTScript(t *testing.T, addr, name string) []string {
	t.Helper()
	c, pr, pw := joinPlayBlackbox(t, addr, name)
	defer c.Close()
	_ = c.SetDeadline(time.Time{})
	sink := newChatSink(pr, pw)
	time.Sleep(3 * time.Second)
	sink.take()

	return runItemProbeScript(t, pw, sink, itemSNBTScript)
}
