// TestItemSNBTParity pins the item-modifier grammar: every reply the
// real server gives for an `item modify` modifier that is not a working
// loot function, compared component for component. The cases come from
// twenty-two differential rounds against the live 26.2 server, each
// probing the error the parser raises first and the exact cursor it
// points at: which token a failure names, whether an overflow echoes
// stripped digits, where a bad zero or separator wants its fix. What is
// not here is the one thing the rounds showed mc-go cannot do yet: a
// modifier that parses but must then run, `{function:"minecraft:set_count",
// count:2}`, which the real server applies to the stack and mc-go only
// accepts. Everything else the rounds tried now matches, including the
// twenty-nine cases this suite shares with TestItemCommandParity's own
// script, which stay there and are not repeated.
//
// Each block resets the probed slot first, so blocks do not see each
// other: the only block that depends on the slot's contents is round 4's
// empty-slot window, kept verbatim with its restore.
func TestItemSNBTParity(t *testing.T) {
	const probe = "ItemSNBTParity"
	tg := requireBlackboxFiles(t, nil, map[string]string{
		"ops.json": opsJSONFor(probe),
	}, nil)
	defer tg.cleanup()
	defer func() {
		if t.Failed() {
			vanillaLogTail(t)
		}
	}()

	want := runItemSNBTScript(t, tg.vanilla, probe)
	got := runItemSNBTScript(t, tg.mcgo, probe)
	for i := range itemSNBTScript {
		if want[i] == got[i] {
			continue
		}
		t.Errorf("%q: mc-go and vanilla disagree\n  vanilla: %s\n  mc-go:   %s",
			itemSNBTScript[i], want[i], got[i])
	}
}

